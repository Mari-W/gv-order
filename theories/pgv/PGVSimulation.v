Theorem pgv_deadlock_free_source M p :
  pgv_frag [] p M PUnit → deadlock_free (∅, {[+ M +]}).
Proof.
  intros HM q Hq.
  assert (prel (∅, {[+ M +]}) (∅, {[+ pgv_eta M +]})) as Hp.
  { split; [done|]. simpl.
    replace ({[+ M +]} : gmultiset expr) with ({[+ M +]} ⊎ (∅ : gmultiset expr)) by multiset_solver.
    replace ({[+ pgv_eta M +]} : gmultiset expr)
      with ({[+ pgv_eta M +]} ⊎ (∅ : gmultiset expr)) by multiset_solver.
    constructor; [apply rel_eta|constructor]. }
  destruct (sim_star _ _ _ Hq Hp) as (q' & Hq' & Hp').
  eapply final; [exact Hp'|]. intros q'' Hq''. apply (pgv_deadlock_free M p HM). by etrans.
Qed.
