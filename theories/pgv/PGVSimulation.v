(** * Deadlock freedom of PGV programs, by simulation

    [pgv_deadlock_free] (PGVTranslate.v) makes the translation
    [pgv_eta M] of a closed program M deadlock free. This file carries
    that back to M in the same semantics ([pgv_deadlock_free_source]).

    - [rel s t] relates a term to its translation. It is the congruence
      generated by k ~ k and k ~ [kon_eta k] on the constants, so it
      relates M to [pgv_eta M] ([rel_eta]). It is closed under renaming,
      substitution and the substitution of a channel.
    - Every step of M is matched by steps of the translation ([fwd]).
      λz. k z takes one β step before the step of k. new takes two β
      steps before it creates the channel and three after.
    - When no thread of M takes a β, new or spawn step, β steps bring
      every thread of the translation to the action of its thread in M
      ([norm]). A step of the translation is then a step of M ([final]).

    The relation has no administrative forms, because the forward
    simulation runs every administrative step at once and the final
    argument needs only the action of a thread. *)

From stdpp Require Import base gmap gmultiset relations.
From LRGV Require Import lang.ThreadSim.
From LRGV Require Export pgv.PGVTranslate.

Set Default Proof Using "All".

(** ** The relation *)

Inductive rel : expr → expr → Prop :=
  | rl_var x : rel (Var x) (Var x)
  | rl_unit : rel EUnit EUnit
  | rl_konst k : rel (Konst k) (Konst k)
  | rl_eta k : rel (Konst k) (kon_eta k)
  | rl_chan c : rel (Chan c) (Chan c)
  | rl_lam e e' : rel e e' → rel (Lam e) (Lam e')
  | rl_app e1 e2 e1' e2' : rel e1 e1' → rel e2 e2' → rel (App e1 e2) (App e1' e2')
  | rl_pair e1 e2 e1' e2' : rel e1 e1' → rel e2 e2' → rel (Pair e1 e2) (Pair e1' e2')
  | rl_letu e1 e2 e1' e2' : rel e1 e1' → rel e2 e2' → rel (LetU e1 e2) (LetU e1' e2')
  | rl_letp e1 e2 e1' e2' : rel e1 e1' → rel e2 e2' → rel (LetP e1 e2) (LetP e1' e2')
  | rl_inj1 e e' : rel e e' → rel (Inj1 e) (Inj1 e')
  | rl_inj2 e e' : rel e e' → rel (Inj2 e) (Inj2 e')
  | rl_case e e1 e2 e' e1' e2' :
      rel e e' → rel e1 e1' → rel e2 e2' → rel (Case e e1 e2) (Case e' e1' e2')
  | rl_box e e' : rel e e' → rel (EBox e) (EBox e').

Lemma rel_refl e : rel e e.
Proof. induction e; constructor; done. Qed.

Lemma rel_eta M : rel M (pgv_eta M).
Proof.
  induction M as [x| |k|c|e IH|e1 IH1 e2 IH2|e1 IH1 e2 IH2|e1 IH1 e2 IH2|e1 IH1 e2 IH2
                 |e IH|e IH|e IH e1 IH1 e2 IH2|e IH]; simpl; try (constructor; done).
  destruct e1; try (apply rl_app; [exact IH1|exact IH2]).
  apply rl_app; [destruct (comm k); constructor|exact IH2].
Qed.

(** ** The translated constants are closed values *)

Lemma kon_eta_rename r k : rename r (kon_eta k) = kon_eta k.
Proof. by destruct k. Qed.

Lemma kon_eta_subst σ k : subst σ (kon_eta k) = kon_eta k.
Proof. by destruct k. Qed.

Lemma kon_eta_chsubst c d k : chsubst c d (kon_eta k) = kon_eta k.
Proof. by destruct k. Qed.

Lemma kon_eta_val k : is_val (kon_eta k).
Proof. by destruct k. Qed.

Lemma kon_eta_fchans k : fchans (kon_eta k) = ∅.
Proof. destruct k; unfold kon_eta, new_tr, let_new_pair, let_new; simpl; set_solver. Qed.

Ltac eta_absurd := match goal with
  | H : kon_eta ?k = _ |- _ => destruct k; discriminate H
  | H : _ = kon_eta ?k |- _ => destruct k; discriminate H
  end.

(** ** Facts about the relation *)

Lemma rel_val s t : rel s t → is_val t = is_val s.
Proof.
  induction 1; simpl; rewrite ?IHrel, ?IHrel1, ?IHrel2; try done. by destruct k.
Qed.

Lemma rel_is_val s t : rel s t → is_val s → is_val t.
Proof. intros H Hv. by rewrite (rel_val _ _ H). Qed.

Lemma rel_fchans s t : rel s t → fchans t = fchans s.
Proof.
  induction 1; simpl; rewrite ?IHrel, ?IHrel1, ?IHrel2, ?IHrel3; try done. apply kon_eta_fchans.
Qed.

Lemma rel_fchans_sub s t : rel s t → fchans t ⊆ fchans s.
Proof. intros H. by rewrite (rel_fchans _ _ H). Qed.

Lemma rel_rename s t : rel s t → ∀ r, rel (rename r s) (rename r t).
Proof.
  induction 1; intros r; simpl; try (constructor; auto; fail).
  rewrite kon_eta_rename. apply rl_eta.
Qed.

Lemma rel_up σ σ' : (∀ x, rel (σ x) (σ' x)) → ∀ x, rel (up σ x) (up σ' x).
Proof. intros H [|x]; simpl; [constructor|]. unfold compose. by apply rel_rename. Qed.

Lemma rel_subst s t : rel s t → ∀ σ σ', (∀ x, rel (σ x) (σ' x)) → rel (subst σ s) (subst σ' t).
Proof.
  induction 1; intros σ σ' Hσ; simpl; [done|..]; try (constructor; auto using rel_up; fail).
  rewrite kon_eta_subst. apply rl_eta.
Qed.

Lemma rel_chsubst c d s t : rel s t → rel (chsubst c d s) (chsubst c d t).
Proof.
  induction 1; simpl; try (constructor; done). rewrite kon_eta_chsubst. apply rl_eta.
Qed.

(** Inversion from the left. *)

Lemma rel_konst_inv k t : rel (Konst k) t → t = Konst k ∨ t = kon_eta k.
Proof. inversion 1; auto. Qed.
Lemma rel_unit_l t : rel EUnit t → t = EUnit.
Proof. by inversion 1. Qed.
Lemma rel_chan_l c t : rel (Chan c) t → t = Chan c.
Proof. by inversion 1. Qed.
Lemma rel_lam_l b t : rel (Lam b) t → ∃ b', t = Lam b' ∧ rel b b'.
Proof. inversion 1; eauto. Qed.
Lemma rel_box_l b t : rel (EBox b) t → ∃ b', t = EBox b' ∧ rel b b'.
Proof. inversion 1; eauto. Qed.
Lemma rel_inj1_l v t : rel (Inj1 v) t → ∃ w, t = Inj1 w ∧ rel v w.
Proof. inversion 1; eauto. Qed.
Lemma rel_inj2_l v t : rel (Inj2 v) t → ∃ w, t = Inj2 w ∧ rel v w.
Proof. inversion 1; eauto. Qed.
Lemma rel_app_l s1 s2 t : rel (App s1 s2) t → ∃ t1 t2, t = App t1 t2 ∧ rel s1 t1 ∧ rel s2 t2.
Proof. inversion 1; eauto. Qed.
Lemma rel_pair_l s1 s2 t : rel (Pair s1 s2) t → ∃ t1 t2, t = Pair t1 t2 ∧ rel s1 t1 ∧ rel s2 t2.
Proof. inversion 1; eauto. Qed.
Lemma rel_letu_l s1 s2 t : rel (LetU s1 s2) t → ∃ t1 t2, t = LetU t1 t2 ∧ rel s1 t1 ∧ rel s2 t2.
Proof. inversion 1; eauto. Qed.
Lemma rel_letp_l s1 s2 t : rel (LetP s1 s2) t → ∃ t1 t2, t = LetP t1 t2 ∧ rel s1 t1 ∧ rel s2 t2.
Proof. inversion 1; eauto. Qed.
Lemma rel_case_l s s1 s2 t :
  rel (Case s s1 s2) t → ∃ t0 t1 t2, t = Case t0 t1 t2 ∧ rel s t0 ∧ rel s1 t1 ∧ rel s2 t2.
Proof. inversion 1; eauto 10. Qed.

(** Inversion from the right. *)

Lemma rel_unit_r s : rel s EUnit → s = EUnit.
Proof. inversion 1; subst; try done; eta_absurd. Qed.
Lemma rel_chan_r s c : rel s (Chan c) → s = Chan c.
Proof. inversion 1; subst; try done; eta_absurd. Qed.
Lemma rel_box_r s b : rel s (EBox b) → ∃ b', s = EBox b'.
Proof. inversion 1; subst; eauto; eta_absurd. Qed.
Lemma rel_inj1_r s w : rel s (Inj1 w) → ∃ v, s = Inj1 v.
Proof. inversion 1; subst; eauto; eta_absurd. Qed.
Lemma rel_inj2_r s w : rel s (Inj2 w) → ∃ v, s = Inj2 v.
Proof. inversion 1; subst; eauto; eta_absurd. Qed.
Lemma rel_pair_r s a b : rel s (Pair a b) → ∃ a' b', s = Pair a' b' ∧ rel a' a ∧ rel b' b.
Proof. inversion 1; subst; eauto; eta_absurd. Qed.

(** ** What a step of M asks of the translation *)

Definition post (α : tlabel) (t : expr) (Q : expr → Prop) : Prop :=
  match α with
  | LBeta => ∃ t', bstar t t' ∧ Q t'
  | LNew c => ∃ t0 t1 t', bstar t t0 ∧ tstep t0 (LNew c) t1 ∧ bstar t1 t' ∧ Q t'
  | LSpawn v => ∃ w t0 t1, rel v w ∧ bstar t t0 ∧ tstep t0 (LSpawn w) t1 ∧ Q t1
  | LSess (SSend c v) => ∃ w t0 t1, rel v w ∧ bstar t t0 ∧ tstep t0 (LSess (SSend c w)) t1 ∧ Q t1
  | LSess (SRecv c v) => ∃ t0, bstar t t0 ∧
      ∀ w, is_val w → rel v w → ∃ t1, tstep t0 (LSess (SRecv c w)) t1 ∧ Q t1
  | LSess σ => ∃ t0 t1, bstar t t0 ∧ tstep t0 (LSess σ) t1 ∧ Q t1
  end.

Lemma post_ectx α t Q Q' K :
  ectx K → post α t Q → (∀ t', Q t' → Q' (K t')) → post α (K t) Q'.
Proof.
  intros HK Hp HQ. destruct α as [|[c v|c v|c|cd]|c|v]; simpl in *.
  - destruct Hp as (t' & Hs & Hq). exists (K t'). split; [by apply bstar_ectx|auto].
  - destruct Hp as (t0 & Hs & Hw). exists (K t0). split; [by apply bstar_ectx|].
    intros w Hv Hr. destruct (Hw w Hv Hr) as (t1 & H1 & Hq). exists (K t1). split; [by apply HK|auto].
  - destruct Hp as (w & t0 & t1 & Hr & Hs & H1 & Hq). exists w, (K t0), (K t1).
    split_and!; [done|by apply bstar_ectx|by apply HK|auto].
  - destruct Hp as (t0 & t1 & Hs & H1 & Hq). exists (K t0), (K t1).
    split_and!; [by apply bstar_ectx|by apply HK|auto].
  - destruct Hp as (t0 & t1 & Hs & H1 & Hq). exists (K t0), (K t1).
    split_and!; [by apply bstar_ectx|by apply HK|auto].
  - destruct Hp as (t0 & t1 & t' & Hs & H1 & Hs' & Hq). exists (K t0), (K t1), (K t').
    split_and!; [by apply bstar_ectx|by apply HK|by apply bstar_ectx|auto].
  - destruct Hp as (w & t0 & t1 & Hr & Hs & H1 & Hq). exists w, (K t0), (K t1).
    split_and!; [done|by apply bstar_ectx|by apply HK|auto].
Qed.

Lemma ectx_pairl e2 : ectx (λ x, Pair x e2).
Proof. intros ???. apply TStepPairL. Qed.
Lemma ectx_pairr v : is_val v → ectx (λ x, Pair v x).
Proof. intros ????. by apply TStepPairR. Qed.
Lemma ectx_letu e2 : ectx (λ x, LetU x e2).
Proof. intros ???. apply TStepLetU. Qed.
Lemma ectx_letp e2 : ectx (λ x, LetP x e2).
Proof. intros ???. apply TStepLetP. Qed.
Lemma ectx_inj1 : ectx Inj1.
Proof. intros ???. apply TStepInj1. Qed.
Lemma ectx_inj2 : ectx Inj2.
Proof. intros ???. apply TStepInj2. Qed.

(** ** The administrative steps *)

(** λz. k z applied to a value. *)
Lemma konst_pre k t1 w :
  comm k = true → is_val w → rel (Konst k) t1 → bstar (App t1 w) (App (Konst k) w).
Proof.
  intros Hk Hw Hr. apply rel_konst_inv in Hr as [->| ->]; [apply rtc_refl|].
  rewrite (kon_eta_comm k Hk). apply rtc_once, TStepHead.
  change (App (Konst k) w) with (subst1 w (App (Konst k) (Var 0))). by apply HeadApp.
Qed.

(** [new_tr] applied to unit. Two β steps, the channel, three β steps. *)
Lemma new_tr_run c :
  ∃ t0 t1, bstar (App new_tr EUnit) t0 ∧ tstep t0 (LNew c) t1 ∧ bstar t1 (Pair (Chan c) (Chan c)).
Proof.
  set (K := LetU (Var 0) (LetP (Var 1) (Pair (Var 1) (Var 0)))).
  exists (LetP (Pair (App ENew EUnit) EUnit) K), (LetP (Pair (Pair (Chan c) (Chan c)) EUnit) K).
  split_and!.
  - eapply rtc_l; [apply TStepHead, (HeadApp _ EUnit); done|].
    apply rtc_once, TStepHead, HeadLetU.
  - apply TStepLetP, TStepPairL, TStepHead, HeadNew.
  - eapply rtc_l; [apply TStepHead, HeadLetP; done|].
    eapply rtc_l; [apply TStepHead, HeadLetU|].
    apply rtc_once, TStepHead, (HeadLetP (Chan c) (Chan c)); done.
Qed.

(** ** Forward simulation of one thread *)

Lemma fwd_head s t α s' : rel s t → head_step s α s' → post α t (rel s').
Proof.
  intros Hr Hh.
  destruct Hh as [e v Hv|e|u v e Hu Hv|c|v Hv|c v Hv|v c Hv|c|v e1 e2 Hv|v e1 e2 Hv|e|c d]; simpl.
  - (* β *)
    destruct (rel_app_l _ _ _ Hr) as (t1 & t2 & -> & H1 & H2).
    destruct (rel_lam_l _ _ H1) as (b' & -> & Hb).
    exists (subst1 t2 b'). split.
    + apply rtc_once, TStepHead, HeadApp. by apply (rel_is_val v).
    + apply rel_subst; [done|]. intros [|x]; simpl; [done|constructor].
  - (* let ∗ *)
    destruct (rel_letu_l _ _ _ Hr) as (t1 & t2 & -> & H1 & H2). apply rel_unit_l in H1 as ->.
    exists t2. split; [apply rtc_once, TStepHead, HeadLetU|done].
  - (* let pair *)
    destruct (rel_letp_l _ _ _ Hr) as (t1 & t2 & -> & H1 & H2).
    destruct (rel_pair_l _ _ _ H1) as (u' & v' & -> & Hu' & Hv').
    exists (subst2 u' v' t2). split.
    + apply rtc_once, TStepHead, HeadLetP; [by apply (rel_is_val u)|by apply (rel_is_val v)].
    + apply rel_subst; [done|]. intros [|[|x]]; simpl; [done|done|constructor].
  - (* new *)
    destruct (rel_app_l _ _ _ Hr) as (t1 & t2 & -> & H1 & H2). apply rel_unit_l in H2 as ->.
    apply rel_konst_inv in H1 as [->| ->].
    + exists (App ENew EUnit), (Pair (Chan c) (Chan c)), (Pair (Chan c) (Chan c)).
      split_and!; [apply rtc_refl|apply TStepHead, HeadNew|apply rtc_refl|apply rel_refl].
    + destruct (new_tr_run c) as (t0 & t1 & H0 & H1 & H2).
      exists t0, t1, (Pair (Chan c) (Chan c)). split_and!; [exact H0|exact H1|exact H2|apply rel_refl].
  - (* spawn *)
    destruct (rel_app_l _ _ _ Hr) as (t1 & t2 & -> & H1 & H2).
    assert (t1 = ESpawn) as -> by (by destruct (rel_konst_inv _ _ H1) as [->| ->]).
    exists t2, (App ESpawn t2), EUnit. split_and!; [done|apply rtc_refl| |constructor].
    apply TStepHead, HeadSpawn. by apply (rel_is_val v).
  - (* recv *)
    destruct (rel_app_l _ _ _ Hr) as (t1 & t2 & -> & H1 & H2). apply rel_chan_l in H2 as ->.
    exists (App ERecv (Chan c)). split; [by apply konst_pre|].
    intros w Hw Hrw. exists (Pair w (Chan c)). split; [by apply TStepHead, HeadRecv|].
    constructor; [done|constructor].
  - (* send *)
    destruct (rel_app_l _ _ _ Hr) as (t1 & t2 & -> & H1 & H2).
    destruct (rel_pair_l _ _ _ H2) as (w & c' & -> & Hw & Hc). apply rel_chan_l in Hc as ->.
    assert (is_val w) as Hwv by (by apply (rel_is_val v)).
    exists w, (App ESend (Pair w (Chan c))), (Chan c). split_and!.
    + done.
    + apply konst_pre; [done| |done]. by apply andb_True.
    + by apply TStepHead, HeadSend.
    + constructor.
  - (* close *)
    destruct (rel_app_l _ _ _ Hr) as (t1 & t2 & -> & H1 & H2). apply rel_chan_l in H2 as ->.
    exists (App EClos (Chan c)), EUnit.
    split_and!; [by apply konst_pre|apply TStepHead, HeadClos|constructor].
  - (* case, left *)
    destruct (rel_case_l _ _ _ _ Hr) as (t0 & e1' & e2' & -> & H0 & H1 & H2).
    destruct (rel_inj1_l _ _ H0) as (w & -> & Hw).
    exists (subst1 w e1'). split.
    + apply rtc_once, TStepHead, HeadCase1. by apply (rel_is_val v).
    + apply rel_subst; [done|]. intros [|x]; simpl; [done|constructor].
  - (* case, right *)
    destruct (rel_case_l _ _ _ _ Hr) as (t0 & e1' & e2' & -> & H0 & H1 & H2).
    destruct (rel_inj2_l _ _ H0) as (w & -> & Hw).
    exists (subst1 w e2'). split.
    + apply rtc_once, TStepHead, HeadCase2. by apply (rel_is_val v).
    + apply rel_subst; [done|]. intros [|x]; simpl; [done|constructor].
  - (* force *)
    destruct (rel_app_l _ _ _ Hr) as (t1 & t2 & -> & H1 & H2).
    assert (t1 = EForce) as -> by (by destruct (rel_konst_inv _ _ H1) as [->| ->]).
    destruct (rel_box_l _ _ H2) as (e' & -> & He).
    exists (subst1 (EBox e') e'). split; [apply rtc_once, TStepHead, HeadForce|].
    apply rel_subst; [done|]. intros [|x]; simpl; [by constructor|constructor].
  - (* link *)
    destruct (rel_app_l _ _ _ Hr) as (t1 & t2 & -> & H1 & H2).
    assert (t1 = ELink) as -> by (by destruct (rel_konst_inv _ _ H1) as [->| ->]).
    destruct (rel_pair_l _ _ _ H2) as (c' & d' & -> & Hc & Hd).
    apply rel_chan_l in Hc as ->. apply rel_chan_l in Hd as ->.
    exists (App ELink (Pair (Chan c) (Chan d))), EUnit.
    split_and!; [apply rtc_refl|apply TStepHead, HeadLink|constructor].
Qed.

Lemma fwd s t α s' : rel s t → tstep s α s' → post α t (rel s').
Proof.
  intros Hr Hst. revert t Hr.
  induction Hst as [e α e' Hh|e1 α e1' e2 Hst IH|v e2 α e2' Hv Hst IH
                   |e1 α e1' e2 Hst IH|v e2 α e2' Hv Hst IH
                   |e1 α e1' e2 Hst IH|e1 α e1' e2 Hst IH
                   |e α e' Hst IH|e α e' Hst IH|e α e' e1 e2 Hst IH]; intros t Hr.
  - by apply (fwd_head e).
  - destruct (rel_app_l _ _ _ Hr) as (t1 & t2 & -> & H1 & H2).
    eapply (post_ectx _ _ _ _ (λ x, App x t2)); [apply ectx_appl|by apply IH|].
    intros t' Ht'. by constructor.
  - destruct (rel_app_l _ _ _ Hr) as (t1 & t2 & -> & H1 & H2).
    eapply (post_ectx _ _ _ _ (λ x, App t1 x)); [apply ectx_appr; by apply (rel_is_val v)|by apply IH|].
    intros t' Ht'. by constructor.
  - destruct (rel_pair_l _ _ _ Hr) as (t1 & t2 & -> & H1 & H2).
    eapply (post_ectx _ _ _ _ (λ x, Pair x t2)); [apply ectx_pairl|by apply IH|].
    intros t' Ht'. by constructor.
  - destruct (rel_pair_l _ _ _ Hr) as (t1 & t2 & -> & H1 & H2).
    eapply (post_ectx _ _ _ _ (λ x, Pair t1 x)); [apply ectx_pairr; by apply (rel_is_val v)|by apply IH|].
    intros t' Ht'. by constructor.
  - destruct (rel_letu_l _ _ _ Hr) as (t1 & t2 & -> & H1 & H2).
    eapply (post_ectx _ _ _ _ (λ x, LetU x t2)); [apply ectx_letu|by apply IH|].
    intros t' Ht'. by constructor.
  - destruct (rel_letp_l _ _ _ Hr) as (t1 & t2 & -> & H1 & H2).
    eapply (post_ectx _ _ _ _ (λ x, LetP x t2)); [apply ectx_letp|by apply IH|].
    intros t' Ht'. by constructor.
  - destruct (rel_inj1_l _ _ Hr) as (t1 & -> & H1).
    eapply (post_ectx _ _ _ _ Inj1); [apply ectx_inj1|by apply IH|].
    intros t' Ht'. by constructor.
  - destruct (rel_inj2_l _ _ Hr) as (t1 & -> & H1).
    eapply (post_ectx _ _ _ _ Inj2); [apply ectx_inj2|by apply IH|].
    intros t' Ht'. by constructor.
  - destruct (rel_case_l _ _ _ _ Hr) as (t0 & t1 & t2 & -> & H0 & H1 & H2).
    eapply (post_ectx _ _ _ _ (λ x, Case x t1 t2)); [apply ectx_case|by apply IH|].
    intros t' Ht'. by constructor.
Qed.

(** ** Processes *)

Definition prel (p q : proc) : Prop := p.1 = q.1 ∧ mrel rel p.2 q.2.

Lemma sim_step p p' q : preduction p p' → prel p q → ∃ q', pred_star q q' ∧ prel p' q'.
Proof.
  destruct p as [C Es], q as [Cq Et]. unfold preduction.
  intros Hs (HC & Hm). simpl in HC, Hm. subst Cq.
  inversion Hs as [|C0 E e e' Hst|C0 E e c e' Hst HcC HcE Hce|C0 E e v e' Hst
                  |C0 E c v e e' f f' Hse Hsf|C0 E c e e' f f' Hse Hsf HcC
                  |C0 E e c d e' Hst HcC]; subst.
  - (* β *)
    destruct (mrel_extract_l _ _ _ _ Hm) as (Et0 & t & -> & HR & Hm0).
    destruct (fwd _ _ _ _ HR Hst) as (t' & Hs' & Hq).
    exists (C, Et0 ⊎ {[+ t' +]}). split; [by apply bstar_proc|].
    split; [done|]. by apply mrel_snoc.
  - (* new *)
    destruct (mrel_extract_l _ _ _ _ Hm) as (Et0 & t & -> & HR & Hm0).
    destruct (fwd _ _ _ _ HR Hst) as (t0 & t1 & t' & Hs0 & Ht & Hs1 & Hq).
    exists (C ∪ {[c]}, Et0 ⊎ {[+ t' +]}). split.
    + eapply rtc_trans; [by apply bstar_proc|].
      eapply rtc_l; [apply PStepNew; [exact Ht|done| |]|by apply bstar_proc].
      * pose proof (mrel_echans _ _ _ rel_fchans_sub Hm0). set_solver.
      * apply bstar_fchans in Hs0. pose proof (rel_fchans _ _ HR). set_solver.
    + split; [done|]. by apply mrel_snoc.
  - (* spawn *)
    destruct (mrel_extract_l _ _ _ _ Hm) as (Et0 & t & -> & HR & Hm0).
    destruct (fwd _ _ _ _ HR Hst) as (w & t0 & t1 & Hrw & Hs0 & Ht & Hq).
    exists (C, Et0 ⊎ {[+ t1 +]} ⊎ {[+ App w EUnit +]}). split.
    + eapply rtc_trans; [by apply bstar_proc|]. apply rtc_once. by apply PStepSpawn.
    + split; [done|]. apply mrel_snoc; [constructor; [done|constructor]|]. by apply mrel_snoc.
  - (* message *)
    destruct (mrel_extract_l _ _ _ _ Hm) as (Et1 & tf & -> & HRf & Hm1).
    destruct (mrel_extract_l _ _ _ _ Hm1) as (Et0 & te & -> & HRe & Hm0).
    destruct (fwd _ _ _ _ HRe Hse) as (w & te0 & te1 & Hrw & Hse0 & Hte & Hqe).
    destruct (fwd _ _ _ _ HRf Hsf) as (tf0 & Hsf0 & Hw).
    destruct (Hw w (tstep_send_val _ _ _ _ Hte) Hrw) as (tf1 & Htf & Hqf).
    exists (C, Et0 ⊎ {[+ te1 +]} ⊎ {[+ tf1 +]}). split.
    + eapply rtc_trans; [by apply bstar_proc2|]. eapply rtc_trans; [by apply bstar_proc|].
      apply rtc_once. by eapply PStepMsg.
    + split; [done|]. apply mrel_snoc; [done|]. by apply mrel_snoc.
  - (* close *)
    destruct (mrel_extract_l _ _ _ _ Hm) as (Et1 & tf & -> & HRf & Hm1).
    destruct (mrel_extract_l _ _ _ _ Hm1) as (Et0 & te & -> & HRe & Hm0).
    destruct (fwd _ _ _ _ HRe Hse) as (te0 & te1 & Hse0 & Hte & Hqe).
    destruct (fwd _ _ _ _ HRf Hsf) as (tf0 & tf1 & Hsf0 & Htf & Hqf).
    exists (C ∖ {[c]}, Et0 ⊎ {[+ te1 +]} ⊎ {[+ tf1 +]}). split.
    + eapply rtc_trans; [by apply bstar_proc2|]. eapply rtc_trans; [by apply bstar_proc|].
      apply rtc_once. by eapply PStepClose.
    + split; [done|]. apply mrel_snoc; [done|]. by apply mrel_snoc.
  - (* link *)
    destruct (mrel_extract_l _ _ _ _ Hm) as (Et0 & t & -> & HR & Hm0).
    destruct (fwd _ _ _ _ HR Hst) as (t0 & t1 & Hs0 & Ht & Hq).
    exists (C ∖ {[c]}, echsubst c d (Et0 ⊎ {[+ t1 +]})). split.
    + eapply rtc_trans; [by apply bstar_proc|]. apply rtc_once. by apply PStepLink.
    + split; [done|]. unfold echsubst. apply mrel_map; [intros; by apply rel_chsubst|].
      by apply mrel_snoc.
Qed.

Lemma sim_star p p' q : rtc preduction p p' → prel p q → ∃ q', pred_star q q' ∧ prel p' q'.
Proof.
  intros H. revert q. induction H as [|p1 p2 p3 H12 _ IH]; intros q Hp; [by exists q|].
  destruct (sim_step _ _ _ H12 Hp) as (q2 & Hq2 & Hp2).
  destruct (IH _ Hp2) as (q3 & Hq3 & Hp3). exists q3. split; [by etrans|done].
Qed.

(** ** Administrative steps bring the translation to the action of M *)

(** The kind of an action, without the values it carries. *)
Definition akind (a : action) : action :=
  match a with ASpawn _ => ASpawn EUnit | ASend c _ => ASend c EUnit | a => a end.

(** A thread that steps without a partner. *)
Definition solo (s : expr) : Prop :=
  act s = Some ABeta ∨ act s = Some ANew ∨ ∃ v, act s = Some (ASpawn v).

Lemma solo_dec s : solo s ∨ ¬ solo s.
Proof.
  unfold solo. destruct (act s) as [[]|].
  1-3: left; eauto.
  all: right; intros [H|[H|[? H]]]; discriminate H.
Qed.

(** t offers the action of s, and is a value or unit only when s is. *)
Definition aligned (s t : expr) : Prop :=
  akind <$> act s = akind <$> act t ∧ (is_val t → is_val s) ∧ (t = EUnit → s = EUnit).

Lemma aligned_refl s : aligned s s.
Proof. split_and!; auto. Qed.

Lemma rel_aligned s t : rel s t → act s = None → act t = None → aligned s t.
Proof.
  intros Hr Hs Ht. split_and!.
  - by rewrite Hs, Ht.
  - intros Hv. by rewrite <-(rel_val _ _ Hr).
  - intros ->. by apply rel_unit_r.
Qed.

Lemma aligned_nval s t : aligned s t → is_val s = false → is_val t = false.
Proof.
  intros (_ & Hv & _) Hs. destruct (is_val t) eqn:E; [|done]. exfalso.
  specialize (Hv I). rewrite Hs in Hv. by destruct Hv.
Qed.

(** An evaluation context around a thread that is no value. *)
Lemma aligned_ctx s t s0 t0 :
  aligned s t → act s0 = act s → act t0 = act t → is_val t0 = false → t0 ≠ EUnit →
  aligned s0 t0.
Proof.
  intros (Ha & _ & _) E1 E2 Hv0 Hne. split_and!.
  - by rewrite E1, E2.
  - rewrite Hv0. by intros [].
  - intros E. by destruct Hne.
Qed.

Lemma aligned_app s1 s2 t1 t2 :
  akind <$> act (App s1 s2) = akind <$> act (App t1 t2) → aligned (App s1 s2) (App t1 t2).
Proof. intros H. split_and!; [done|by intros []|done]. Qed.

Lemma act_app_l e1 e2 : is_val e1 = false → act (App e1 e2) = act e1.
Proof. intros H. simpl. by rewrite H. Qed.
Lemma act_app_r e1 e2 : is_val e1 = true → is_val e2 = false → act (App e1 e2) = act e2.
Proof. intros H1 H2. simpl. by rewrite H1, H2. Qed.
Lemma act_pair_l e1 e2 : is_val e1 = false → act (Pair e1 e2) = act e1.
Proof. intros H. simpl. by rewrite H. Qed.
Lemma act_pair_r e1 e2 : is_val e1 = true → act (Pair e1 e2) = act e2.
Proof. intros H. simpl. by rewrite H. Qed.
Lemma act_letu_l e1 e2 : is_val e1 = false → act (LetU e1 e2) = act e1.
Proof. intros H. simpl. by rewrite H. Qed.
Lemma act_letp_l e1 e2 : is_val e1 = false → act (LetP e1 e2) = act e1.
Proof. intros H. simpl. by rewrite H. Qed.
Lemma act_case_l e e1 e2 : is_val e = false → act (Case e e1 e2) = act e.
Proof. intros H. simpl. by rewrite H. Qed.

Lemma act_letu_val e1 e2 : is_val e1 → e1 ≠ EUnit → act (LetU e1 e2) = None.
Proof. intros Hv Hne. simpl. rewrite (is_val_true _ Hv). destruct e1; done. Qed.
Lemma act_letp_val e1 e2 : is_val e1 → (∀ a b, e1 ≠ Pair a b) → act (LetP e1 e2) = None.
Proof. intros Hv Hne. simpl. rewrite (is_val_true _ Hv). destruct e1; try done. by destruct (Hne e1_1 e1_2). Qed.
Lemma act_case_val e e1 e2 :
  is_val e → (∀ v, e ≠ Inj1 v) → (∀ v, e ≠ Inj2 v) → act (Case e e1 e2) = None.
Proof.
  intros Hv H1 H2. simpl. rewrite (is_val_true _ Hv). destruct e; try done.
  - by destruct (H1 e). - by destruct (H2 e).
Qed.

(** An action is a step. *)
Lemma act_some_step e a : act e = Some a → ∃ α e', tstep e α e'.
Proof.
  intros H. destruct a as [| |v|c|c v|c|c d].
  all: first [ destruct (act_offer e _ LBeta H I) as [e' ?]
             | destruct (act_offer e _ (LNew inhabitant) H I) as [e' ?]
             | destruct (act_offer e _ (LSpawn v) H eq_refl) as [e' ?]
             | destruct (act_offer e _ (LSess (SRecv c EUnit)) H (conj eq_refl I)) as [e' ?]
             | destruct (act_offer e _ (LSess (SSend c v)) H (conj eq_refl eq_refl)) as [e' ?]
             | destruct (act_offer e _ (LSess (SClos c)) H eq_refl) as [e' ?]
             | destruct (act_offer e _ (LSess (SLink {[c; d]})) H eq_refl) as [e' ?] ];
    eauto.
Qed.

Lemma act_app_none e1 e2 :
  is_val e1 → is_val e2 → (∀ α e', ¬ head_step (App e1 e2) α e') → act (App e1 e2) = None.
Proof.
  intros H1 H2 Hh. destruct (act (App e1 e2)) eqn:E; [|done]. exfalso.
  destruct (act_some_step _ _ E) as (α & e' & Hst). apply app_val_step in Hst; [|done|done].
  by apply (Hh α e').
Qed.

(** A constant applied to a value, the same constant on both sides. *)
Lemma act_konst_some k u a :
  is_val u → act (App (Konst k) u) = Some a →
  (k = KNew ∧ u = EUnit) ∨ (k = KSpawn ∧ a = ASpawn u) ∨
  (∃ c, k = KRecv ∧ u = Chan c ∧ a = ARecv c) ∨
  (∃ c x, k = KSend ∧ u = Pair x (Chan c) ∧ a = ASend c x) ∨
  (∃ c, k = KClos ∧ u = Chan c ∧ a = AClos c) ∨
  (∃ c d, k = KLink ∧ u = Pair (Chan c) (Chan d) ∧ a = ALink c d) ∨
  (∃ e, k = KForce ∧ u = EBox e ∧ a = ABeta).
Proof.
  intros Hu H. simpl in H. rewrite (is_val_true _ Hu) in H.
  destruct k; destruct u as [| | | | | |u1 u2| | | | | |]; simpl in H; try discriminate H;
    try (destruct u2; try discriminate H); try (destruct u1; try discriminate H);
    injection H as <-; eauto 20.
Qed.

Lemma head_same k v w :
  rel v w → is_val v → solo (App (Konst k) v) ∨ aligned (App (Konst k) v) (App (Konst k) w).
Proof.
  intros Hr Hv. pose proof (rel_is_val _ _ Hr Hv) as Hw.
  destruct (act (App (Konst k) v)) as [a|] eqn:Ea.
  - destruct (act_konst_some _ _ _ Hv Ea)
      as [(-> & ->)|[(-> & ->)|[(c & -> & -> & ->)|[(c & x & -> & -> & ->)
         |[(c & -> & -> & ->)|[(c & d & -> & -> & ->)|(e & -> & -> & ->)]]]]]].
    + left. right; left. done.
    + left. right; right. by eexists.
    + right. apply rel_chan_l in Hr as ->. apply aligned_app. by rewrite Ea.
    + right. destruct (rel_pair_l _ _ _ Hr) as (x' & c' & -> & Hx & Hc).
      apply rel_chan_l in Hc as ->. apply aligned_app. rewrite Ea.
      apply andb_True in Hw as [Hx' _].
      destruct (act_step _ _ _ (TStepHead _ _ _ (HeadSend x' c Hx'))) as (b & Hb & Ho).
      apply offers_send in Ho as ->. by rewrite Hb.
    + right. apply rel_chan_l in Hr as ->. apply aligned_app. by rewrite Ea.
    + right. destruct (rel_pair_l _ _ _ Hr) as (c' & d' & -> & Hc & Hd).
      apply rel_chan_l in Hc as ->. apply rel_chan_l in Hd as ->. apply aligned_app. by rewrite Ea.
    + left. by left.
  - right. apply aligned_app. rewrite Ea.
    destruct (act (App (Konst k) w)) as [b|] eqn:Eb; [|done]. exfalso.
    assert (∀ α e', tstep (App (Konst k) v) α e' → False) as Hn.
    { intros α e' Hst. destruct (act_step _ _ _ Hst) as (? & ? & _). congruence. }
    destruct (act_konst_some _ _ _ Hw Eb)
      as [(-> & ->)|[(-> & ->)|[(c & -> & -> & ->)|[(c & x & -> & -> & ->)
         |[(c & -> & -> & ->)|[(c & d & -> & -> & ->)|(e & -> & -> & ->)]]]]]].
    + apply rel_unit_r in Hr as ->. apply (Hn _ _ (TStepHead _ _ _ (HeadNew inhabitant))).
    + apply (Hn _ _ (TStepHead _ _ _ (HeadSpawn v Hv))).
    + apply rel_chan_r in Hr as ->. apply (Hn _ _ (TStepHead _ _ _ (HeadRecv c EUnit I))).
    + destruct (rel_pair_r _ _ _ Hr) as (x0 & c0 & -> & _ & Hc). apply rel_chan_r in Hc as ->.
      apply andb_True in Hv as [Hx0 _]. apply (Hn _ _ (TStepHead _ _ _ (HeadSend x0 c Hx0))).
    + apply rel_chan_r in Hr as ->. apply (Hn _ _ (TStepHead _ _ _ (HeadClos c))).
    + destruct (rel_pair_r _ _ _ Hr) as (c0 & d0 & -> & Hc & Hd).
      apply rel_chan_r in Hc as ->. apply rel_chan_r in Hd as ->.
      apply (Hn _ _ (TStepHead _ _ _ (HeadLink c d))).
    + destruct (rel_box_r _ _ Hr) as (e0 & ->). apply (Hn _ _ (TStepHead _ _ _ (HeadForce e0))).
Qed.

Lemma head_konst k t1 v w :
  rel (Konst k) t1 → rel v w → is_val v →
  solo (App (Konst k) v) ∨ ∃ t', bstar (App t1 w) t' ∧ aligned (App (Konst k) v) t'.
Proof.
  intros H1 Hr Hv. pose proof (rel_is_val _ _ Hr Hv) as Hw.
  destruct (comm k) eqn:Ek.
  { destruct (head_same k v w Hr Hv) as [?|Ha]; [by left|right].
    exists (App (Konst k) w). split; [by apply konst_pre|done]. }
  destruct (rel_konst_inv _ _ H1) as [->| ->].
  { destruct (head_same k v w Hr Hv) as [?|Ha]; [by left|right].
    exists (App (Konst k) w). split; [apply rtc_refl|done]. }
  destruct (decide (k = KNew)) as [->|Hk].
  - destruct (decide (v = EUnit)) as [->|Hne]; [left; by right; left|right].
    assert (w ≠ EUnit) as Hne' by (intros ->; by apply Hne, rel_unit_r).
    eexists. split.
    { apply rtc_once, TStepHead. change (kon_eta KNew) with new_tr. unfold new_tr.
      by apply HeadApp. }
    unfold subst1. simpl. split_and!; [|by intros []|done].
    rewrite act_letu_val by done.
    destruct (act (App ENew v)) as [a|] eqn:Ea; [|done].
    destruct (act_konst_some _ _ _ Hv Ea) as [(_ & ?)|[(? & _)|[(? & ? & _)|[(? & ? & ? & _)
      |[(? & ? & _)|[(? & ? & ? & _)|(? & ? & _)]]]]]]; done.
  - destruct (head_same k v w Hr Hv) as [?|Ha]; [by left|right].
    exists (App (Konst k) w). split; [|done].
    replace (kon_eta k) with (Konst k) by (destruct k; try reflexivity; simpl in Ek; congruence).
    apply rtc_refl.
Qed.

Lemma norm s t : rel s t → solo s ∨ ∃ t', bstar t t' ∧ aligned s t'.
Proof.
  induction 1 as [x| |k|k|c|e e' H IH|e1 e2 e1' e2' H1 IH1 H2 IH2|e1 e2 e1' e2' H1 IH1 H2 IH2
                 |e1 e2 e1' e2' H1 IH1 H2 IH2|e1 e2 e1' e2' H1 IH1 H2 IH2|e e' H IH|e e' H IH
                 |e e1 e2 e' e1' e2' H IH H1 IH1 H2 IH2|e e' H IH].
  - right. eexists. split; [apply rtc_refl|apply aligned_refl].
  - right. eexists. split; [apply rtc_refl|apply aligned_refl].
  - right. eexists. split; [apply rtc_refl|apply aligned_refl].
  - right. exists (kon_eta k). split; [apply rtc_refl|].
    apply rel_aligned; [apply rl_eta|done|]. apply act_val, kon_eta_val.
  - right. eexists. split; [apply rtc_refl|apply aligned_refl].
  - right. exists (Lam e'). split; [apply rtc_refl|]. apply rel_aligned; [by constructor|done|done].
  - (* application *)
    destruct (is_val e1) eqn:Hv1.
    2:{ destruct IH1 as [Hs|(t1 & Hb & Ha)].
        - left. unfold solo in *. by rewrite act_app_l.
        - right. exists (App t1 e2'). split.
          + apply (bstar_ectx (λ x, App x e2')); [apply ectx_appl|done].
          + eapply aligned_ctx; [exact Ha|by apply act_app_l| |done|done].
            apply act_app_l. by eapply aligned_nval. }
    assert (is_val e1' = true) as Hv1' by (by rewrite (rel_val _ _ H1)).
    destruct (is_val e2) eqn:Hv2.
    2:{ destruct IH2 as [Hs|(t2 & Hb & Ha)].
        - left. unfold solo in *. by rewrite act_app_r.
        - right. exists (App e1' t2). split.
          + apply (bstar_ectx (λ x, App e1' x)); [apply ectx_appr; by rewrite Hv1'|done].
          + eapply aligned_ctx; [exact Ha|by apply act_app_r| |done|done].
            apply act_app_r; [done|by eapply aligned_nval]. }
    assert (is_val e2' = true) as Hv2' by (by rewrite (rel_val _ _ H2)).
    assert (∀ s1 t1, rel s1 t1 → is_val s1 →
              (∀ α e', ¬ head_step (App s1 e2) α e') → (∀ α e', ¬ head_step (App t1 e2') α e') →
              ∃ t', bstar (App t1 e2') t' ∧ aligned (App s1 e2) t') as Hinert.
    { intros s1 t1 Hr Hs Hn1 Hn2. exists (App t1 e2'). split; [apply rtc_refl|].
      apply rel_aligned; [by constructor|apply act_app_none; [done|by rewrite Hv2|done]|].
      apply act_app_none; [by apply (rel_is_val s1)|by rewrite Hv2'|done]. }
    destruct e1 as [| |k| |b| | | | | | | |]; simpl in Hv1; try discriminate Hv1.
    + apply rel_unit_l in H1 as ->. right. apply Hinert; [constructor|done|inversion 1|inversion 1].
    + apply head_konst; [done|done|by rewrite Hv2].
    + apply rel_chan_l in H1 as ->. right. apply Hinert; [constructor|done|inversion 1|inversion 1].
    + left. left. simpl. by rewrite Hv2.
    + destruct (rel_pair_l _ _ _ H1) as (a & b & -> & Ha & Hb). right.
      apply Hinert; [done|simpl; by rewrite Hv1|inversion 1|inversion 1].
    + destruct (rel_inj1_l _ _ H1) as (a & -> & Ha). right.
      apply Hinert; [done|simpl; by rewrite Hv1|inversion 1|inversion 1].
    + destruct (rel_inj2_l _ _ H1) as (a & -> & Ha). right.
      apply Hinert; [done|simpl; by rewrite Hv1|inversion 1|inversion 1].
    + destruct (rel_box_l _ _ H1) as (a & -> & Ha). right.
      apply Hinert; [done|done|inversion 1|inversion 1].
  - (* pair *)
    destruct (is_val e1) eqn:Hv1.
    2:{ destruct IH1 as [Hs|(t1 & Hb & Ha)].
        - left. unfold solo in *. by rewrite act_pair_l.
        - right. exists (Pair t1 e2'). split.
          + apply (bstar_ectx (λ x, Pair x e2')); [apply ectx_pairl|done].
          + eapply aligned_ctx; [exact Ha|by apply act_pair_l| | |done].
            * apply act_pair_l. by eapply aligned_nval.
            * simpl. by rewrite (aligned_nval _ _ Ha Hv1). }
    assert (is_val e1' = true) as Hv1' by (by rewrite (rel_val _ _ H1)).
    destruct (is_val e2) eqn:Hv2.
    2:{ destruct IH2 as [Hs|(t2 & Hb & Ha)].
        - left. unfold solo in *. by rewrite act_pair_r.
        - right. exists (Pair e1' t2). split.
          + apply (bstar_ectx (λ x, Pair e1' x)); [apply ectx_pairr; by rewrite Hv1'|done].
          + eapply aligned_ctx; [exact Ha|by apply act_pair_r|by apply act_pair_r| |done].
            simpl. by rewrite Hv1', (aligned_nval _ _ Ha Hv2). }
    right. exists (Pair e1' e2'). split; [apply rtc_refl|].
    apply rel_aligned; [by constructor| |]; apply act_val; simpl.
    + by rewrite Hv1, Hv2.
    + by rewrite Hv1', (rel_val _ _ H2), Hv2.
  - (* let ∗ *)
    destruct (is_val e1) eqn:Hv1.
    2:{ destruct IH1 as [Hs|(t1 & Hb & Ha)].
        - left. unfold solo in *. by rewrite act_letu_l.
        - right. exists (LetU t1 e2'). split.
          + apply (bstar_ectx (λ x, LetU x e2')); [apply ectx_letu|done].
          + eapply aligned_ctx; [exact Ha|by apply act_letu_l| |done|done].
            apply act_letu_l. by eapply aligned_nval. }
    destruct (decide (e1 = EUnit)) as [->|Hne]; [left; by left|right].
    exists (LetU e1' e2'). split; [apply rtc_refl|].
    apply rel_aligned; [by constructor|apply act_letu_val; [by rewrite Hv1|done]|].
    apply act_letu_val; [by apply (rel_is_val e1); [|rewrite Hv1]|].
    intros ->. by apply Hne, rel_unit_r.
  - (* let pair *)
    destruct (is_val e1) eqn:Hv1.
    2:{ destruct IH1 as [Hs|(t1 & Hb & Ha)].
        - left. unfold solo in *. by rewrite act_letp_l.
        - right. exists (LetP t1 e2'). split.
          + apply (bstar_ectx (λ x, LetP x e2')); [apply ectx_letp|done].
          + eapply aligned_ctx; [exact Ha|by apply act_letp_l| |done|done].
            apply act_letp_l. by eapply aligned_nval. }
    assert ((∃ a b, e1 = Pair a b) ∨ ∀ a b, e1 ≠ Pair a b) as [(a & b & ->)|Hnp].
    { destruct e1; try (right; intros ? ? [=]; fail). left. eauto. }
    { left. left. simpl. simpl in Hv1. by rewrite Hv1. }
    right. exists (LetP e1' e2'). split; [apply rtc_refl|].
    apply rel_aligned; [by constructor|apply act_letp_val; [by rewrite Hv1|done]|].
    apply act_letp_val; [by apply (rel_is_val e1); [|rewrite Hv1]|].
    intros a b ->. destruct (rel_pair_r _ _ _ H1) as (a' & b' & -> & _). by apply (Hnp a' b').
  - (* inj₁ *)
    destruct IH as [Hs|(t1 & Hb & (Hk & Hv & Hu))]; [left; done|right].
    exists (Inj1 t1). split; [apply (bstar_ectx Inj1); [apply ectx_inj1|done]|].
    split_and!; [done|simpl; exact Hv|done].
  - (* inj₂ *)
    destruct IH as [Hs|(t1 & Hb & (Hk & Hv & Hu))]; [left; done|right].
    exists (Inj2 t1). split; [apply (bstar_ectx Inj2); [apply ectx_inj2|done]|].
    split_and!; [done|simpl; exact Hv|done].
  - (* case *)
    destruct (is_val e) eqn:Hv.
    2:{ destruct IH as [Hs|(t0 & Hb & Ha)].
        - left. unfold solo in *. by rewrite act_case_l.
        - right. exists (Case t0 e1' e2'). split.
          + apply (bstar_ectx (λ x, Case x e1' e2')); [apply ectx_case|done].
          + eapply aligned_ctx; [exact Ha|by apply act_case_l| |done|done].
            apply act_case_l. by eapply aligned_nval. }
    assert ((∃ v, e = Inj1 v) ∨ (∃ v, e = Inj2 v) ∨ ((∀ v, e ≠ Inj1 v) ∧ (∀ v, e ≠ Inj2 v)))
      as [(v & ->)|[(v & ->)|(Hn1 & Hn2)]].
    { destruct e; try (right; right; split; intros ? [=]; fail); eauto. }
    { left. left. simpl. simpl in Hv. by rewrite Hv. }
    { left. left. simpl. simpl in Hv. by rewrite Hv. }
    right. exists (Case e' e1' e2'). split; [apply rtc_refl|].
    apply rel_aligned; [by constructor|apply act_case_val; [by rewrite Hv|done|done]|].
    apply act_case_val; [by apply (rel_is_val e); [|rewrite Hv]| |].
    + intros v ->. destruct (rel_inj1_r _ _ H) as (v' & ->). by apply (Hn1 v').
    + intros v ->. destruct (rel_inj2_r _ _ H) as (v' & ->). by apply (Hn2 v').
  - right. exists (EBox e'). split; [apply rtc_refl|]. apply rel_aligned; [by constructor|done|done].
Qed.

Lemma norm_ms Es Et :
  mrel rel Es Et →
  (∃ s, s ∈ Es ∧ solo s) ∨ ∃ Et', rtc msb Et Et' ∧ mrel (λ s t, ¬ solo s ∧ aligned s t) Es Et'.
Proof.
  induction 1 as [|s t Es Et HR Hm IH].
  - right. exists ∅. split; [done|constructor].
  - destruct (solo_dec s) as [Hs|Hns].
    { left. exists s. split; [multiset_solver|done]. }
    destruct (norm _ _ HR) as [?|(t' & Hst & Ha)]; [done|].
    destruct IH as [(s0 & Hs0 & Hsolo)|(Et' & Hst' & Hm')].
    { left. exists s0. split; [multiset_solver|done]. }
    right. exists ({[+ t' +]} ⊎ Et'). split; [|by constructor].
    apply (rtc_trans _ ({[+ t' +]} ⊎ Et)).
    + rewrite (comm_L (⊎) {[+ t +]}), (comm_L (⊎) {[+ t' +]}). by apply msb_bstar.
    + by apply msb_frame.
Qed.

Lemma aligned_step s t β t' :
  aligned s t → tstep t β t' → ∃ a b, act s = Some a ∧ akind a = akind b ∧ offers b β.
Proof.
  intros (Ha & _ & _) Hst. destruct (act_step _ _ _ Hst) as (b & Hb & Ho).
  rewrite Hb in Ha. destruct (act s) as [a|]; [|done]. injection Ha as Ha. eauto.
Qed.

Lemma offers_clos a c : offers a (LSess (SClos c)) → a = AClos c.
Proof. destruct a; simpl; intros H; try done; by subst. Qed.

Lemma final p q : prel p q → (∀ q', pred_star q q' → safe q') → safe p.
Proof.
  destruct p as [C Es], q as [Cq Et]. intros (HC & Hm) Hsafe. simpl in HC, Hm. subst Cq.
  destruct (norm_ms _ _ Hm) as [(s & Hs & Hsolo)|(Et' & Hst & Hm')].
  - (* a thread of M steps alone *)
    right. destruct (gmultiset_split1 _ _ Hs) as [E0 ->].
    destruct Hsolo as [Ha|[Ha|[v Ha]]].
    + destruct (act_offer s ABeta LBeta Ha I) as [s' Hs']. eexists. by apply PStepBeta.
    + set (c := fresh (C ∪ echans E0 ∪ fchans s)).
      assert (c ∉ C ∪ echans E0 ∪ fchans s) by apply is_fresh.
      destruct (act_offer s ANew (LNew c) Ha I) as [s' Hs'].
      eexists. apply PStepNew; [exact Hs'|set_solver..].
    + destruct (act_offer s (ASpawn v) (LSpawn v) Ha eq_refl) as [s' Hs'].
      eexists. by apply PStepSpawn.
  - destruct (Hsafe (C, Et') (msb_pred _ _ _ Hst)) as [Hterm|(q'' & Hred)].
    + (* the translation has terminated *)
      left. destruct Hterm as (v & E1 & [= -> ->] & Hv & HE1).
      rewrite (comm_L (⊎) {[+ v +]} E1) in Hm'.
      destruct (mrel_extract _ _ _ _ Hm') as (Es0 & s & -> & (_ & _ & Hvs & _) & Hm0).
      exists s, Es0. split_and!; [f_equal; multiset_solver|by apply Hvs|].
      intros e He. destruct (mrel_elem_l _ _ _ _ Hm0 He) as (t & Ht & (_ & _ & _ & Hu)).
      apply Hu. by apply HE1.
    + (* a step of the translation is a step of M *)
      right. unfold preduction in Hred.
      inversion Hred as [|C0 E0 e e' Hste|C0 E0 e c e' Hste|C0 E0 e v e' Hste
                        |C0 E0 c v e e' f f' Hse Hsf|C0 E0 c e e' f f' Hse Hsf Hc
                        |C0 E0 e c d e' Hste Hc]; subst.
      * destruct (mrel_extract _ _ _ _ Hm') as (Es0 & s & -> & (Hns & Ha) & _).
        destruct (aligned_step _ _ _ _ Ha Hste) as (a & b & Ea & Hk & Ho).
        exfalso. destruct b; simpl in Ho; try done.
        destruct a; simpl in Hk; try discriminate Hk. apply Hns. by left.
      * destruct (mrel_extract _ _ _ _ Hm') as (Es0 & s & -> & (Hns & Ha) & _).
        destruct (aligned_step _ _ _ _ Ha Hste) as (a & b & Ea & Hk & Ho).
        exfalso. destruct b; simpl in Ho; try done.
        destruct a; simpl in Hk; try discriminate Hk. apply Hns. by right; left.
      * destruct (mrel_extract _ _ _ _ Hm') as (Es0 & s & -> & (Hns & Ha) & _).
        destruct (aligned_step _ _ _ _ Ha Hste) as (a & b & Ea & Hk & Ho).
        exfalso. destruct b; simpl in Ho; try done.
        destruct a; simpl in Hk; try discriminate Hk. apply Hns. right; right. by eexists.
      * destruct (mrel_extract _ _ _ _ Hm') as (Es1 & sf & -> & (_ & Haf) & Hm1).
        destruct (mrel_extract _ _ _ _ Hm1) as (Es0 & se & -> & (_ & Hae) & _).
        destruct (aligned_step _ _ _ _ Hae Hse) as (ae & be & Eae & Hke & Hoe).
        destruct (aligned_step _ _ _ _ Haf Hsf) as (af & bf & Eaf & Hkf & Hof).
        apply offers_send in Hoe as ->. apply offers_recv in Hof as ->.
        destruct ae as [| | |?|c0 v0|?|? ?]; simpl in Hke; try discriminate Hke.
        injection Hke as ->.
        destruct af; simpl in Hkf; try discriminate Hkf. injection Hkf as ->.
        destruct (act_offer se (ASend c v0) (LSess (SSend c v0)) Eae (conj eq_refl eq_refl))
          as [se' Hse'].
        destruct (act_offer sf (ARecv c) (LSess (SRecv c v0)) Eaf
                    (conj eq_refl (tstep_send_val _ _ _ _ Hse'))) as [sf' Hsf'].
        eexists. by eapply PStepMsg.
      * destruct (mrel_extract _ _ _ _ Hm') as (Es1 & sf & -> & (_ & Haf) & Hm1).
        destruct (mrel_extract _ _ _ _ Hm1) as (Es0 & se & -> & (_ & Hae) & _).
        destruct (aligned_step _ _ _ _ Hae Hse) as (ae & be & Eae & Hke & Hoe).
        destruct (aligned_step _ _ _ _ Haf Hsf) as (af & bf & Eaf & Hkf & Hof).
        apply offers_clos in Hoe as ->. apply offers_clos in Hof as ->.
        destruct ae; simpl in Hke; try discriminate Hke. injection Hke as ->.
        destruct af; simpl in Hkf; try discriminate Hkf. injection Hkf as ->.
        destruct (act_offer se (AClos c) (LSess (SClos c)) Eae eq_refl) as [se' Hse'].
        destruct (act_offer sf (AClos c) (LSess (SClos c)) Eaf eq_refl) as [sf' Hsf'].
        eexists. by eapply PStepClose.
      * destruct (mrel_extract _ _ _ _ Hm') as (Es0 & s & -> & (_ & Ha) & _).
        destruct (aligned_step _ _ _ _ Ha Hste) as (a & b & Ea & Hk & Ho).
        destruct b as [| | | | | |c0 d0]; simpl in Ho; try done.
        destruct a; simpl in Hk; try discriminate Hk. injection Hk as -> ->.
        destruct (act_offer s (ALink c0 d0) (LSess (SLink {[c; d]})) Ea Ho) as [s' Hs'].
        eexists. by apply PStepLink.
Qed.

