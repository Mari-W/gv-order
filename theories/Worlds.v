(** * Worlds: aliases and a strict order on instants (§5)

    A world W = (≡, ≺) relates instants (p, b), i.e. points. ≡ is an
    equivalence of aliases, closed under shifting both sides
    (p@a ≡ q@b means (p, a+n) ≡ (q, b+n) for all n), and ≺ is a
    transitive order on ≡-classes that contains program order
    (p, b) ≺ (p, b+1). A world is strict when ≺ is irreflexive. Worlds
    are the Kripke index of the logical relation.

    A world carries its support: the names its facts mention. Outside
    the support only reflexivity and program order hold. The support
    is what Amalgamation restricts to and what a fresh extension at
    [new] avoids.

    Worlds are relations ([Prop]-valued), so that the world generated
    by a set of schemas (Typing.v) and the join of two worlds are both
    plain inductive closures ([wgen]). *)

From stdpp Require Import base gmap relations.
From LRGV Require Export Types.

Notation prel := (point → point → Prop).

Record world := World {
  w_names : gset pname;
  w_eq : prel;
  w_lt : prel
}.

(** The root name of a point: a slot ι[i] belongs to the name of ι.
    The support is counted on root names (channels and point
    variables), so that slot congruence does not need infinitely many
    slot names in a finite support. *)
Fixpoint pn_root (p : pname) : pname :=
  match p with
  | NSlot q _ _ => pn_root q
  | _ => p
  end.

Definition pt_root (x : point) : pname := pn_root (pt_name x).

Lemma pt_root_shift n x : pt_root (pt_shift n x) = pt_root x.
Proof. done. Qed.

Lemma pt_root_slot x i : pt_root (pt_slot x i) = pt_root x.
Proof. done. Qed.

(** Facts between two points either are trivial or involve names of
    the support only. *)
Definition eq_or_supp (N : gset pname) (x y : point) : Prop :=
  x = y ∨ (pt_root x ∈ N ∧ pt_root y ∈ N).

Definition po_or_supp (N : gset pname) (x y : point) : Prop :=
  (pt_name x = pt_name y ∧ pt_off x < pt_off y) ∨
  (pt_root x ∈ N ∧ pt_root y ∈ N).

Record world_wf (W : world) : Prop := {
  wf_eq_refl x : w_eq W x x;
  wf_eq_sym x y : w_eq W x y → w_eq W y x;
  wf_eq_trans x y z : w_eq W x y → w_eq W y z → w_eq W x z;
  wf_eq_shift x y : w_eq W x y → w_eq W (pt_shift 1 x) (pt_shift 1 y);
  wf_eq_slot x y i : w_eq W x y → w_eq W (pt_slot x i) (pt_slot y i);
  wf_lt_trans x y z : w_lt W x y → w_lt W y z → w_lt W x z;
  wf_lt_eq x x' y y' : w_eq W x x' → w_lt W x' y' → w_eq W y' y → w_lt W x y;
  wf_lt_po x : w_lt W x (pt_shift 1 x);
  wf_eq_supp x y : w_eq W x y → eq_or_supp (w_names W) x y;
  wf_lt_supp x y : w_lt W x y → po_or_supp (w_names W) x y
}.

Definition strict (W : world) : Prop :=
  world_wf W ∧ ∀ x, ¬ w_lt W x x.

(** p@a ≡ q@b, the alias. *)
Definition w_alias (W : world) (x y : point) : Prop :=
  ∀ n, w_eq W (pt_shift n x) (pt_shift n y).

(** ≼ = ≺ or ≡. *)
Definition w_le (W : world) (x y : point) : Prop := w_eq W x y ∨ w_lt W x y.

(** F ≺ G between sets of points (frames). *)
Definition w_lt_set (W : world) (X Y : gset point) : Prop :=
  ∀ x y, x ∈ X → y ∈ Y → w_lt W x y.

(** {β} ≺ F for an upper point (⊥ = [None] is below everything) and
    {λ} ≼ H for a lower point (⊤ = [None] is below nothing, so it forces
    H = ∅: a closure without a lower bound holds nothing). *)
Definition ub_below (W : world) (ub : option point) (F : gset point) : Prop :=
  match ub with None => True | Some x => ∀ y, y ∈ F → w_lt W x y end.

Definition lb_below (W : world) (lb : option point) (H : gset point) : Prop :=
  match lb with None => H = ∅ | Some x => ∀ y, y ∈ H → w_le W x y end.

(** ** The world generated by facts

    [wgen N E L]: the least world with support N whose ≡ contains E and
    whose ≺ contains L. *)

Inductive geq (E : prel) : prel :=
  | geq_base x y : E x y → geq E x y
  | geq_refl x : geq E x x
  | geq_sym x y : geq E x y → geq E y x
  | geq_trans x y z : geq E x y → geq E y z → geq E x z
  | geq_shift x y : geq E x y → geq E (pt_shift 1 x) (pt_shift 1 y)
  | geq_slot x y i : geq E x y → geq E (pt_slot x i) (pt_slot y i).

Inductive glt (E L : prel) : prel :=
  | glt_base x y : L x y → glt E L x y
  | glt_po x : glt E L x (pt_shift 1 x)
  | glt_eq x x' y y' : geq E x x' → glt E L x' y' → geq E y' y → glt E L x y
  | glt_trans x y z : glt E L x y → glt E L y z → glt E L x z.

Definition wgen (N : gset pname) (E L : prel) : world :=
  World N (geq E) (glt E L).

Lemma pt_name_shift n x : pt_name (pt_shift n x) = pt_name x.
Proof. done. Qed.

Lemma geq_supp N E x y :
  (∀ x y, E x y → eq_or_supp N x y) → geq E x y → eq_or_supp N x y.
Proof.
  intros HE. unfold eq_or_supp.
  induction 1 as [x y Hb|x|x y _ IH|x y z _ IH1 _ IH2|x y _ IH|x y i _ IH];
    [by apply HE|by left|naive_solver|naive_solver| |].
  - destruct IH as [->|[??]]; [by left|right; done].
  - destruct IH as [->|[??]]; [by left|right; done].
Qed.

Lemma glt_supp N E L x y :
  (∀ x y, E x y → eq_or_supp N x y) →
  (∀ x y, L x y → po_or_supp N x y) →
  glt E L x y → po_or_supp N x y.
Proof.
  intros HE HL. unfold po_or_supp.
  induction 1 as [x y Hb|x|x x' y y' Hx _ IH Hy|x y z _ IH1 _ IH2].
  - by apply HL.
  - left. simpl. split; [done|lia].
  - apply (geq_supp N) in Hx; [|done]. apply (geq_supp N) in Hy; [|done].
    unfold eq_or_supp, po_or_supp, pt_root in *.
    destruct Hx as [->|[??]], Hy as [<-|[??]], IH as [[??]|[??]];
      first [left; split; [congruence|lia]|right; split; congruence].
  - unfold po_or_supp, pt_root in *.
    destruct IH1 as [[??]|[??]], IH2 as [[??]|[??]];
      first [left; split; [congruence|lia]|right; split; congruence].
Qed.

Lemma wgen_wf N E L :
  (∀ x y, E x y → eq_or_supp N x y) →
  (∀ x y, L x y → po_or_supp N x y) →
  world_wf (wgen N E L).
Proof.
  intros HE HL. split; simpl.
  - apply geq_refl.
  - apply geq_sym.
  - apply geq_trans.
  - apply geq_shift.
  - apply geq_slot.
  - apply glt_trans.
  - apply glt_eq.
  - apply glt_po.
  - intros x y. by apply geq_supp.
  - intros x y. by apply glt_supp.
Qed.

(** ** Kripke order, fresh extension, join, restriction *)

(** W ⊑ W′. *)
Definition wext (W W' : world) : Prop :=
  w_names W ⊆ w_names W' ∧
  (∀ x y, w_eq W x y → w_eq W' x y) ∧
  (∀ x y, w_lt W x y → w_lt W' x y) ∧
  strict W'.

(** W ⊑ₒ W′ placing the new names N: W′ knows exactly the names of W
    and N, and adds nothing between instants of other names (only at
    [new]). *)
Definition wext_fresh (W : world) (N : gset pname) (W' : world) : Prop :=
  wext W W' ∧ N ## w_names W ∧ w_names W' = w_names W ∪ N ∧
  (∀ x y, pt_root x ∉ N → pt_root y ∉ N →
     (w_eq W' x y → w_eq W x y) ∧ (w_lt W' x y → w_lt W x y)).

(** W₁ ⊔ W₂. *)
Definition wjoin (W1 W2 : world) : world :=
  wgen (w_names W1 ∪ w_names W2)
    (λ x y, w_eq W1 x y ∨ w_eq W2 x y)
    (λ x y, w_lt W1 x y ∨ w_lt W2 x y).

(** W|_A. *)
Definition wrestrict (W : world) (A : gset pname) : world :=
  World (w_names W ∩ A)
    (λ x y, w_eq W x y ∧ eq_or_supp A x y)
    (λ x y, w_lt W x y ∧ po_or_supp A x y).

(** ** Basic facts *)

Lemma eq_or_supp_mono N N' x y :
  N ⊆ N' → eq_or_supp N x y → eq_or_supp N' x y.
Proof. unfold eq_or_supp. set_solver. Qed.

Lemma po_or_supp_mono N N' x y :
  N ⊆ N' → po_or_supp N x y → po_or_supp N' x y.
Proof. unfold po_or_supp. set_solver. Qed.

Lemma wjoin_wf W1 W2 : world_wf W1 → world_wf W2 → world_wf (wjoin W1 W2).
Proof.
  intros H1 H2. apply wgen_wf.
  - intros x y [Hxy|Hxy].
    + eapply (eq_or_supp_mono (w_names W1)); [set_solver|].
      by apply (wf_eq_supp _ H1).
    + eapply (eq_or_supp_mono (w_names W2)); [set_solver|].
      by apply (wf_eq_supp _ H2).
  - intros x y [Hxy|Hxy].
    + eapply (po_or_supp_mono (w_names W1)); [set_solver|].
      by apply (wf_lt_supp _ H1).
    + eapply (po_or_supp_mono (w_names W2)); [set_solver|].
      by apply (wf_lt_supp _ H2).
Qed.

Lemma wjoin_l W1 W2 :
  (∀ x y, w_eq W1 x y → w_eq (wjoin W1 W2) x y) ∧
  (∀ x y, w_lt W1 x y → w_lt (wjoin W1 W2) x y).
Proof.
  split; intros x y H; [apply geq_base|apply glt_base]; by left.
Qed.

Lemma wjoin_r W1 W2 :
  (∀ x y, w_eq W2 x y → w_eq (wjoin W1 W2) x y) ∧
  (∀ x y, w_lt W2 x y → w_lt (wjoin W1 W2) x y).
Proof.
  split; intros x y H; [apply geq_base|apply glt_base]; by right.
Qed.

Lemma wrestrict_wf W A : world_wf W → world_wf (wrestrict W A).
Proof.
  intros HW. split; simpl; unfold eq_or_supp, po_or_supp.
  - intros x. split; [apply (wf_eq_refl _ HW)|by left].
  - intros x y [? Hs]. split; [by apply (wf_eq_sym _ HW)|].
    destruct Hs as [->|[??]]; [by left|by right].
  - intros x y z [? Hs1] [? Hs2]. split; [by eapply (wf_eq_trans _ HW)|].
    destruct Hs1 as [->|[??]], Hs2 as [->|[??]]; [by left|by right..].
  - intros x y [? Hs]. split; [by apply (wf_eq_shift _ HW)|].
    destruct Hs as [->|[??]]; [by left|by right].
  - intros x y i [? Hs]. split; [by apply (wf_eq_slot _ HW)|].
    destruct Hs as [->|[??]]; [by left|by right].
  - intros x y z [? Hs1] [? Hs2]. split; [by eapply (wf_lt_trans _ HW)|].
    destruct Hs1 as [[H1 H1']|[H1 H1']], Hs2 as [[H2 H2']|[H2 H2']].
    + left. split; [congruence|lia].
    + right. split; [unfold pt_root; by rewrite H1|done].
    + right. split; [done|unfold pt_root; by rewrite <-H2].
    + by right.
  - intros x x' y y' [? Hx] [? Hl] [? Hy]. split; [by eapply (wf_lt_eq _ HW)|].
    destruct Hx as [<-|[Hx1 Hx2]], Hy as [->|[Hy1 Hy2]].
    + exact Hl.
    + right. split; [|done].
      destruct Hl as [[He _]|[? _]]; [unfold pt_root; by rewrite He|done].
    + right. split; [done|].
      destruct Hl as [[He _]|[_ ?]]; [unfold pt_root; by rewrite <-He|done].
    + by right.
  - intros x. split; [apply (wf_lt_po _ HW)|]. left. simpl. split; [done|lia].
  - intros x y [Hxy Hs]. apply (wf_eq_supp _ HW) in Hxy.
    destruct Hs as [->|[??]]; [by left|].
    destruct Hxy as [->|[??]]; [by left|].
    right. split; by apply elem_of_intersection.
  - intros x y [Hxy Hs]. apply (wf_lt_supp _ HW) in Hxy.
    destruct Hs as [?|[??]]; [by left|].
    destruct Hxy as [?|[??]]; [by left|].
    right. split; by apply elem_of_intersection.
Qed.

(** An alias is just ≡, because ≡ is closed under shifting. *)
Lemma pt_shift_0 x : pt_shift 0 x = x.
Proof. destruct x. unfold pt_shift. simpl. f_equal. lia. Qed.

Lemma pt_shift_S n x : pt_shift 1 (pt_shift n x) = pt_shift (S n) x.
Proof. destruct x. unfold pt_shift. simpl. f_equal. lia. Qed.

Lemma w_alias_iff W x y : world_wf W → w_alias W x y ↔ w_eq W x y.
Proof.
  intros HW. split.
  - intros H. specialize (H 0). by rewrite !pt_shift_0 in H.
  - intros H n. induction n as [|n IH]; [by rewrite !pt_shift_0|].
    rewrite <-(pt_shift_S n x), <-(pt_shift_S n y).
    by apply (wf_eq_shift _ HW).
Qed.

(** The Kripke order is reflexive on strict worlds and transitive. *)
Lemma wext_refl W : strict W → wext W W.
Proof. intros HW. split_and!; auto. Qed.

Lemma wext_trans W1 W2 W3 : wext W1 W2 → wext W2 W3 → wext W1 W3.
Proof.
  intros (?&H1e&H1l&_) (?&H2e&H2l&?). split_and!; auto. set_solver.
Qed.

(** ** Program order is in every world *)

Lemma wf_lt_po_n W x k : world_wf W → w_lt W x (pt_shift (S k) x).
Proof.
  intros HW. induction k as [|k IH].
  - apply (wf_lt_po _ HW).
  - rewrite <-(pt_shift_S (S k) x).
    eapply (wf_lt_trans _ HW); [exact IH|apply (wf_lt_po _ HW)].
Qed.

Lemma wf_lt_same W x y :
  world_wf W → pt_name x = pt_name y → pt_off x < pt_off y → w_lt W x y.
Proof.
  intros HW Hn Ho. destruct x as [p a], y as [q b]; simpl in *; subst q.
  replace (Pt p b) with (pt_shift (S (b - a - 1)) (Pt p a)).
  - by apply wf_lt_po_n.
  - unfold pt_shift. simpl. f_equal. lia.
Qed.

(** ** Facts with a strictness flag

    [wfact W b x y] is x ≺ y for b = true and x ≡ y for b = false. A
    fact is either universal (reflexivity, program order: it holds in
    every world) or proper (both names in the support). *)

Definition wfact (W : world) (b : bool) (x y : point) : Prop :=
  if b then w_lt W x y else w_eq W x y.

Definition univ (b : bool) (x y : point) : Prop :=
  if b then pt_name x = pt_name y ∧ pt_off x < pt_off y else x = y.

Lemma wfact_trans W b1 b2 x y z :
  world_wf W → wfact W b1 x y → wfact W b2 y z → wfact W (b1 || b2) x z.
Proof.
  intros HW. destruct b1, b2; simpl; intros H1 H2.
  - by eapply (wf_lt_trans _ HW).
  - eapply (wf_lt_eq _ HW); [apply (wf_eq_refl _ HW)|done|done].
  - eapply (wf_lt_eq _ HW); [done|done|apply (wf_eq_refl _ HW)].
  - by eapply (wf_eq_trans _ HW).
Qed.

Lemma univ_wfact W b x y : world_wf W → univ b x y → wfact W b x y.
Proof.
  intros HW. destruct b; simpl.
  - intros [??]. by apply wf_lt_same.
  - intros ->. apply (wf_eq_refl _ HW).
Qed.

Lemma wfact_cases W b x y :
  world_wf W → wfact W b x y →
  univ b x y ∨ (pt_root x ∈ w_names W ∧ pt_root y ∈ w_names W).
Proof.
  intros HW. destruct b; simpl; intros H.
  - by apply (wf_lt_supp _ HW) in H.
  - by apply (wf_eq_supp _ HW) in H.
Qed.

Lemma wfact_restrict W A b x y :
  wfact W b x y → pt_root x ∈ A → pt_root y ∈ A →
  wfact (wrestrict W A) b x y.
Proof.
  destruct b; simpl; intros H Hx Hy; (split; [done|]); by right.
Qed.

Lemma wfact_join_l W1 W2 b x y : wfact W1 b x y → wfact (wjoin W1 W2) b x y.
Proof. destruct b; apply wjoin_l. Qed.

Lemma wfact_join_r W1 W2 b x y : wfact W2 b x y → wfact (wjoin W1 W2) b x y.
Proof. destruct b; apply wjoin_r. Qed.

(** ** Inclusion of generated worlds *)

Lemma wgen_incl E L E' L' :
  (∀ x y, E x y → geq E' x y) →
  (∀ x y, L x y → glt E' L' x y) →
  (∀ x y, geq E x y → geq E' x y) ∧ (∀ x y, glt E L x y → glt E' L' x y).
Proof.
  intros HE HL.
  assert (∀ x y, geq E x y → geq E' x y) as Heq.
  { induction 1; eauto using geq. }
  split; [done|]. induction 1; eauto using glt.
Qed.

(** ** Paths through a join

    A derivation in W₁ ⊔ W₂ is a path of facts of W₁ and W₂; the flag
    records whether some step is strict. *)

Section join_paths.
  Context (W1 W2 : world) (HW1 : world_wf W1) (HW2 : world_wf W2).

  Definition sfact (b : bool) (x y : point) : Prop :=
    wfact W1 b x y ∨ wfact W2 b x y.

  Inductive jpath : bool → point → point → Prop :=
    | jpath_nil x : jpath false x x
    | jpath_cons b1 b2 x y z :
        sfact b1 x y → jpath b2 y z → jpath (b1 || b2) x z.

  Lemma jpath_one b x y : sfact b x y → jpath b x y.
  Proof.
    intros H. rewrite <-(orb_false_r b). econstructor; [done|constructor].
  Qed.

  Lemma jpath_app b1 b2 x y z :
    jpath b1 x y → jpath b2 y z → jpath (b1 || b2) x z.
  Proof.
    induction 1 as [|b1' b2' x y' z' Hs Hp IH]; intros H2; [done|].
    rewrite <-orb_assoc. econstructor; [done|]. by apply IH.
  Qed.

  Lemma jpath_rev x y : jpath false x y → jpath false y x.
  Proof.
    remember false as b eqn:Hb. induction 1 as [|b1 b2 x y z Hs Hp IH];
      [constructor|].
    destruct b1, b2; try discriminate.
    change false with (false || false). eapply jpath_app; [by apply IH|].
    apply jpath_one. destruct Hs as [Hs|Hs]; [left|right];
      by apply wf_eq_sym.
  Qed.

  Lemma jpath_shift x y :
    jpath false x y → jpath false (pt_shift 1 x) (pt_shift 1 y).
  Proof.
    remember false as b eqn:Hb. induction 1 as [|b1 b2 x y z Hs Hp IH];
      [constructor|].
    destruct b1, b2; try discriminate.
    change false with (false || false). econstructor; [|by apply IH].
    destruct Hs as [Hs|Hs]; [left|right]; by apply wf_eq_shift.
  Qed.

  Lemma jpath_slot x y i :
    jpath false x y → jpath false (pt_slot x i) (pt_slot y i).
  Proof.
    remember false as b eqn:Hb. induction 1 as [|b1 b2 x y z Hs Hp IH];
      [constructor|].
    destruct b1, b2; try discriminate.
    change false with (false || false). econstructor; [|by apply IH].
    destruct Hs as [Hs|Hs]; [left|right]; by apply wf_eq_slot.
  Qed.

  Lemma join_jpath :
    (∀ x y, w_eq (wjoin W1 W2) x y → jpath false x y) ∧
    (∀ x y, w_lt (wjoin W1 W2) x y → jpath true x y).
  Proof.
    assert (∀ x y, w_eq (wjoin W1 W2) x y → jpath false x y) as Heq.
    { simpl. induction 1 as [x y Hb|x|x y _ IH|x y z _ IH1 _ IH2|x y _ IH|x y i _ IH].
      - apply jpath_one. done.
      - constructor.
      - by apply jpath_rev.
      - change false with (false || false). by eapply jpath_app.
      - by apply jpath_shift.
      - by apply jpath_slot. }
    split; [done|]. simpl.
    induction 1 as [x y Hb|x|x x' y y' Hx _ IH Hy|x y z _ IH1 _ IH2].
    - by apply jpath_one.
    - apply jpath_one. left. apply (wf_lt_po _ HW1).
    - change true with ((false || true) || false).
      eapply jpath_app; [eapply jpath_app; [by apply Heq|done]|by apply Heq].
    - change true with (true || true). by eapply jpath_app.
  Qed.

  Let A := w_names W1 ∩ w_names W2.
  Let RJ := wjoin (wrestrict W1 A) (wrestrict W2 A).

  Lemma RJ_wf : world_wf RJ.
  Proof. apply wjoin_wf; by apply wrestrict_wf. Qed.

  Lemma sfact_RJ b x y :
    sfact b x y → pt_root x ∈ A → pt_root y ∈ A → wfact RJ b x y.
  Proof.
    intros [H|H] Hx Hy.
    - apply wfact_join_l. by apply wfact_restrict.
    - apply wfact_join_r. by apply wfact_restrict.
  Qed.

  (** Two consecutive side facts compose, or they meet at a shared
      name. *)
  Lemma sfact_combine b1 b2 x y z :
    sfact b1 x y → sfact b2 y z →
    sfact (b1 || b2) x z ∨
    (pt_root y ∈ A ∧ sfact b1 x y ∧ sfact b2 y z).
  Proof.
    intros H1 H2.
    destruct (decide (pt_root y ∈ A)) as [Hy|Hy]; [right; by split_and!|left].
    destruct H1 as [H1|H1], H2 as [H2|H2].
    - left. by apply wfact_trans with y.
    - destruct (wfact_cases _ _ _ _ HW1 H1) as [Hu|[_ Hy1]].
      + right. apply wfact_trans with y; [done|by apply univ_wfact|done].
      + destruct (wfact_cases _ _ _ _ HW2 H2) as [Hu|[Hy2 _]].
        * left. apply wfact_trans with y; [done|done|by apply univ_wfact].
        * exfalso. apply Hy. by apply elem_of_intersection.
    - destruct (wfact_cases _ _ _ _ HW2 H1) as [Hu|[_ Hy2]].
      + left. apply wfact_trans with y; [done|by apply univ_wfact|done].
      + destruct (wfact_cases _ _ _ _ HW1 H2) as [Hu|[Hy1 _]].
        * right. apply wfact_trans with y; [done|done|by apply univ_wfact].
        * exfalso. apply Hy. by apply elem_of_intersection.
    - right. by apply wfact_trans with y.
  Qed.

  (** A path is a single side fact, or it passes through the
      restricted join between two shared names. *)
  Lemma jpath_decomp b x y :
    jpath b x y →
    (∃ b', sfact b' x y ∧ (b = true → b' = true)) ∨
    (∃ a c b1 b2 b3, sfact b1 x a ∧ pt_root a ∈ A ∧ wfact RJ b2 a c ∧
       pt_root c ∈ A ∧ sfact b3 c y ∧ (b = true → b1 || b2 || b3 = true)).
  Proof.
    induction 1 as [x|b0 b x y z Hs Hp IH].
    - left. exists false. split; [left; apply (wf_eq_refl _ HW1)|done].
    - destruct IH as [(b' & Hyz & Hb)|(a & c & b1 & b2 & b3 &
                                      Hya & Ha & Hac & Hc & Hcz & Hb)].
      + destruct (sfact_combine _ _ _ _ _ Hs Hyz) as [Hxz|(Hy & _ & _)].
        * left. exists (b0 || b'). split; [done|].
          destruct b0, b, b'; naive_solver.
        * right. exists y, y, b0, false, b'. split_and!; try done.
          -- destruct b0; simpl; apply (wf_eq_refl _ RJ_wf).
          -- destruct b0, b, b'; naive_solver.
      + destruct (sfact_combine _ _ _ _ _ Hs Hya) as [Hxa|(Hy & _ & _)].
        * right. exists a, c, (b0 || b1), b2, b3. split_and!; try done.
          destruct b0, b, b1, b2, b3; naive_solver.
        * right. exists y, c, b0, (b1 || b2), b3. split_and!; try done.
          -- apply wfact_trans with a; [apply RJ_wf| |done].
             by apply sfact_RJ.
          -- destruct b0, b, b1, b2, b3; naive_solver.
  Qed.

  (** The same decomposition with the flags kept exactly: a path of
      aliases decomposes into aliases. *)
  Lemma jpath_decomp_exact b x y :
    jpath b x y →
    sfact b x y ∨
    (∃ a c b1 b2 b3, sfact b1 x a ∧ pt_root a ∈ A ∧ wfact RJ b2 a c ∧
       pt_root c ∈ A ∧ sfact b3 c y ∧ b1 || b2 || b3 = b).
  Proof.
    induction 1 as [x|b0 b x y z Hs Hp IH].
    - left. left. apply (wf_eq_refl _ HW1).
    - destruct IH as [Hyz|(a & c & b1 & b2 & b3 &
                           Hya & Ha & Hac & Hc & Hcz & <-)].
      + destruct (sfact_combine _ _ _ _ _ Hs Hyz) as [Hxz|(Hy & _ & _)].
        * by left.
        * right. exists y, y, b0, false, b. split_and!; try done.
          -- destruct b0; simpl; apply (wf_eq_refl _ RJ_wf).
          -- by rewrite orb_false_r.
      + destruct (sfact_combine _ _ _ _ _ Hs Hya) as [Hxa|(Hy & _ & _)].
        * right. exists a, c, (b0 || b1), b2, b3. split_and!; try done.
          by rewrite !orb_assoc.
        * right. exists y, c, b0, (b1 || b2), b3. split_and!; try done.
          -- apply wfact_trans with a; [apply RJ_wf| |done].
             by apply sfact_RJ.
          -- by rewrite !orb_assoc.
  Qed.

  (** A cycle in W₁ ⊔ W₂ is a cycle in W₁, in W₂, or in the
      restricted join. *)
  Lemma join_cycle x :
    w_lt (wjoin W1 W2) x x →
    w_lt W1 x x ∨ w_lt W2 x x ∨ ∃ a, w_lt RJ a a.
  Proof.
    intros H. apply (proj2 join_jpath) in H.
    destruct (jpath_decomp _ _ _ H) as [(b' & Hs & Hb)|(a & c & b1 & b2 & b3 &
                                      Hxa & Ha & Hac & Hc & Hcx & Hb)].
    - rewrite (Hb eq_refl) in Hs. destruct Hs; auto.
    - right; right. exists a.
      assert (wfact RJ (b3 || b1) c a) as Hca.
      { destruct (sfact_combine _ _ _ _ _ Hcx Hxa) as [Hca|(Hx & ? & ?)].
        - by apply sfact_RJ.
        - apply wfact_trans with x; [apply RJ_wf|by apply sfact_RJ..]. }
      pose proof (wfact_trans _ _ _ _ _ _ RJ_wf Hac Hca) as Haa.
      specialize (Hb eq_refl).
      by replace (b2 || (b3 || b1)) with true in Haa
        by (destruct b1, b2, b3; naive_solver).
  Qed.
End join_paths.

(** ** Amalgamation

    A join is strict exactly when the join of the two worlds restricted
    to their shared names is strict. Both worlds have to be strict
    themselves: a cycle among names only W₁ knows is invisible to the
    restriction. *)

Lemma wjoin_restrict_incl W1 W2 A :
  (∀ x y, w_eq (wjoin (wrestrict W1 A) (wrestrict W2 A)) x y →
          w_eq (wjoin W1 W2) x y) ∧
  (∀ x y, w_lt (wjoin (wrestrict W1 A) (wrestrict W2 A)) x y →
          w_lt (wjoin W1 W2) x y).
Proof.
  apply wgen_incl.
  - intros x y [[H _]|[H _]]; apply geq_base; [by left|by right].
  - intros x y [[H _]|[H _]]; apply glt_base; [by left|by right].
Qed.

Theorem amalgamation W1 W2 :
  strict W1 → strict W2 →
  strict (wjoin W1 W2) ↔
  strict (wjoin (wrestrict W1 (w_names W1 ∩ w_names W2))
                (wrestrict W2 (w_names W1 ∩ w_names W2))).
Proof.
  intros [HW1 Hi1] [HW2 Hi2]. split.
  - intros [_ Hi]. split; [apply wjoin_wf; by apply wrestrict_wf|].
    intros x Hx. apply (Hi x). by apply (proj2 (wjoin_restrict_incl W1 W2 (w_names W1 ∩ w_names W2))).
  - intros [_ Hi]. split; [by apply wjoin_wf|].
    intros x Hx.
    destruct (join_cycle W1 W2 HW1 HW2 x Hx) as [?|[?|[a Ha]]];
      [by eapply Hi1|by eapply Hi2|by eapply Hi].
Qed.

(** ** Fresh extension

    Placing fresh names N in W₁ keeps a strict join strict, provided W₂
    does not know N. *)

Theorem fresh_extension W1 N W1' W2 :
  wext_fresh W1 N W1' → N ## w_names W2 → strict W2 →
  strict (wjoin W1 W2) → strict (wjoin W1' W2).
Proof.
  intros [(_ & _ & _ & HW1') [HN [_ Hold]]] HN2 HW2 [HJ Hi].
  apply amalgamation; [done..|].
  set (A := w_names W1' ∩ w_names W2).
  assert (∀ x, pt_root x ∈ A → pt_root x ∉ N) as HA.
  { intros x Hx. subst A. set_solver. }
  split; [apply wjoin_wf; apply wrestrict_wf; [apply HW1'|apply HW2]|].
  intros x Hx. apply (Hi x).
  revert Hx. apply wgen_incl.
  - intros a b [[Hab Hs]|[Hab Hs]].
    + destruct Hs as [->|[Ha Hb]]; [apply geq_refl|].
      apply geq_base. left. by apply (Hold a b (HA a Ha) (HA b Hb)).
    + apply geq_base. by right.
  - intros a b [[Hab Hs]|[Hab Hs]].
    + destruct Hs as [[Hn Ho]|[Ha Hb]]; [by apply (wf_lt_same _ a b HJ)|].
      apply glt_base. left. by apply (Hold a b (HA a Ha) (HA b Hb)).
    + apply glt_base. by right.
Qed.

(** A fresh extension survives joining with a larger world that does
    not know the new names: W ⊑ₒ W₁ placing N and W ⊑ W′ give
    W′ ⊑ₒ W₁ ⊔ W′ placing N. Monotonicity of the relation at [new]
    uses it. *)

Lemma wgen_in_world W E L :
  world_wf W →
  (∀ x y, E x y → w_eq W x y) → (∀ x y, L x y → w_lt W x y) →
  (∀ x y, geq E x y → w_eq W x y) ∧ (∀ x y, glt E L x y → w_lt W x y).
Proof.
  intros HW HE HL.
  assert (∀ x y, geq E x y → w_eq W x y) as Heq.
  { induction 1; eauto using wf_eq_refl, wf_eq_sym, wf_eq_trans,
      wf_eq_shift, wf_eq_slot. }
  split; [done|]. induction 1; eauto using wf_lt_trans, wf_lt_po.
  eapply (wf_lt_eq _ HW); eauto.
Qed.

Lemma wjoin_sub_strict W W' :
  wext W W' → strict (wjoin W W').
Proof.
  intros (Hn & He & Hl & [HW' Hi]).
  destruct (wgen_in_world W' (λ x y, w_eq W x y ∨ w_eq W' x y)
              (λ x y, w_lt W x y ∨ w_lt W' x y)) as [Heq Hlt];
    [done|naive_solver|naive_solver|].
  split.
  - apply wgen_wf.
    + intros x y H. assert (w_eq W' x y) as H' by (destruct H; auto).
      eapply eq_or_supp_mono; [|by apply (wf_eq_supp _ HW')].
      apply union_subseteq_r.
    + intros x y H. assert (w_lt W' x y) as H' by (destruct H; auto).
      eapply po_or_supp_mono; [|by apply (wf_lt_supp _ HW')].
      apply union_subseteq_r.
  - intros x Hx. apply (Hi x). by apply Hlt.
Qed.

Lemma wext_fresh_join W N W1 W' :
  world_wf W → wext_fresh W N W1 → wext W W' → N ## w_names W' →
  wext_fresh W' N (wjoin W1 W').
Proof.
  intros HW [(Hn1 & He1 & Hl1 & [HW1 Hi1]) [HN [Hnames Hold]]]
         (Hn' & He' & Hl' & [HW' Hi']) HN'.
  assert (strict (wjoin W1 W')) as Hstr.
  { apply (fresh_extension W N W1 W'); [split_and!; done|done|done|].
    by apply wjoin_sub_strict. }
  set (A := w_names W1 ∩ w_names W').
  assert (∀ x, pt_root x ∈ A → pt_root x ∉ N) as HA.
  { intros x Hx. subst A. set_solver. }
  (* facts of W₁ between points outside N are facts of W' *)
  assert (∀ b x y, wfact W1 b x y → pt_root x ∉ N → pt_root y ∉ N →
            wfact W' b x y) as H1.
  { intros [] x y H Hx Hy; simpl in *.
    - apply Hl'. by apply (Hold x y Hx Hy).
    - apply He'. by apply (Hold x y Hx Hy). }
  assert (∀ b x y, wfact (wjoin (wrestrict W1 A) (wrestrict W' A)) b x y →
            wfact W' b x y) as HRJ.
  { destruct (wgen_in_world W' (λ x y, w_eq (wrestrict W1 A) x y ∨
                                         w_eq (wrestrict W' A) x y)
                (λ x y, w_lt (wrestrict W1 A) x y ∨
                        w_lt (wrestrict W' A) x y)) as [Heq Hlt]; [done| | |].
    - intros x y [[H Hs]|[H Hs]]; [|done].
      destruct Hs as [->|[Hx Hy]]; [apply (wf_eq_refl _ HW')|].
      by apply (H1 false x y); [|apply HA..].
    - intros x y [[H Hs]|[H Hs]]; [|done].
      destruct Hs as [[Hn Ho]|[Hx Hy]]; [by apply wf_lt_same|].
      by apply (H1 true x y); [|apply HA..].
    - intros [] x y H; simpl in *; [by apply Hlt|by apply Heq]. }
  (* a side fact between points outside N is a fact of W' *)
  assert (∀ b x y, sfact W1 W' b x y → pt_root x ∉ N → pt_root y ∉ N →
            wfact W' b x y) as Hs.
  { intros b x y [H|H] Hx Hy; [by apply H1|done]. }
  assert (∀ b x y, jpath W1 W' b x y → pt_root x ∉ N → pt_root y ∉ N →
            wfact W' b x y) as Hpath.
  { intros b x y Hp Hx Hy.
    destruct (jpath_decomp_exact W1 W' HW1 HW' b x y Hp)
      as [Hxy|(a & c & b1 & b2 & b3 & Hxa & Ha & Hac & Hc & Hcy & <-)];
      [by apply Hs|].
    apply (wfact_trans W' (b1 || b2) b3 x c y HW'); [|apply Hs; [done|by apply HA|done]].
    apply (wfact_trans W' b1 b2 x a c HW'); [apply Hs; [done|done|by apply HA]|].
    by apply HRJ. }
  split_and!.
  - split_and!; [simpl; set_solver|by apply wjoin_r..|done].
  - done.
  - simpl. rewrite Hnames. set_solver.
  - intros x y Hx Hy. split.
    + intros H. apply (Hpath false); [|done..].
      by apply (join_jpath W1 W' HW1 HW').
    + intros H. apply (Hpath true); [|done..].
      by apply (join_jpath W1 W' HW1 HW').
Qed.
