    (∀ y, y ∈ P → slt W Ψ x y) →
    match o with Some φ => ∃ u, Φ !! φ = Some (Some u) ∧ sle W Ψ x u | None => True end →
    ub_below_s W Ψ Φ (Some x) (P, o).
  Proof. apply ub_below_s_intro. Qed.

