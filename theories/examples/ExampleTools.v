  Proof. intros HW. apply sl_w, (wf_lt_br _ HW). Qed.
End frames.

(** ** Walks (K10)

    A walk is a list of steps from a point: [None] is the successor
    x+1 and [Some i] the branch root x◁i. The points reachable from ι
    are the ends of the walks from ι, reach(ι) = {ι·w ∣ w}. Constraints
    over reach(ι) quantify over walks. *)
Definition wstep (x : point) (s : option bool) : point :=
  match s with None => pt_shift 1 x | Some i => pt_br x i end.

Fixpoint pwalk (x : point) (w : list (option bool)) : point :=
  match w with [] => x | s :: w' => pwalk (wstep x s) w' end.

Lemma pwalk_app x u v : pwalk x (u ++ v) = pwalk (pwalk x u) v.
Proof. revert x. induction u; intros x; simpl; auto. Qed.

Lemma pwalk_inst σ x w : pt_inst σ (pwalk x w) = pwalk (pt_inst σ x) w.
Proof.
  revert x. induction w as [|[i|] w IH]; intros x; simpl; [done| |]; rewrite IH; f_equal;
    first [apply pt_inst_br|apply pt_inst_shift].
Qed.

Lemma pwalk_root x w : pt_root (pwalk x w) = pt_root x.
Proof. revert x. induction w as [|[i|] w IH]; intros x; simpl; by rewrite ?IH. Qed.

Lemma pwalk_vb k x w : pn_vb k (pt_name x) → pn_vb k (pt_name (pwalk x w)).
Proof. revert x. induction w as [|[i|] w IH]; intros x Hx; simpl; [done|apply IH..]; done. Qed.

Lemma pwalk_ppo x s w : ppo x (pwalk x (s :: w)).
Proof.
  assert (∀ y w, ppo x y → ppo x (pwalk y w)) as H.
  { intros y w'. revert y. induction w' as [|[i|] w' IH]; intros y Hy; simpl; [done| |];
      apply IH; eapply ppo_trans; [exact Hy|apply ppo_br|exact Hy|apply ppo_po]. }
  apply (H (wstep x s) w). destruct s; [apply ppo_br|apply ppo_po].
Qed.

Lemma pwalk_size x w : pt_size (pwalk x w) = pt_size x + length w.
Proof.
  revert x. induction w as [|[i|] w IH]; intros x; simpl; rewrite ?IH;
    unfold pt_size, pt_br, pt_shift; simpl; lia.
Qed.

Lemma slt_walk W Ψ x s w : world_wf W → slt W Ψ x (pwalk x (s :: w)).
Proof. intros HW. apply sl_w, (wf_lt_ppo _ _ _ HW), pwalk_ppo. Qed.

Lemma wstep_inst σ x s : pt_inst σ (wstep x s) = wstep (pt_inst σ x) s.
Proof. destruct s; simpl; [apply pt_inst_br|apply pt_inst_shift]. Qed.

Lemma wstep_root x s : pt_root (wstep x s) = pt_root x.
Proof. by destruct s. Qed.

Lemma wstep_vb k x s : pn_vb k (pt_name x) → pn_vb k (pt_name (wstep x s)).
Proof. by destruct s. Qed.

Lemma wstep_size x s : pt_size (wstep x s) = S (pt_size x).
Proof. destruct s; unfold pt_size, pt_br, pt_shift; simpl; lia. Qed.

