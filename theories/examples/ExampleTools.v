Lemma pwalk_vb k x w : pn_vb k (pt_name x) → pn_vb k (pt_name (pwalk x w)).
Proof. revert x. induction w as [|s w IH]; intros x Hx; simpl; [done|]. apply IH, wstep_vb, Hx. Qed.

