Lemma Wpo_strict cs : strict (Wpo cs).
Proof.
  apply (wgen_strict _ _ _ id (prank (λ _, 1) (λ _, 0) (λ _ _ _, 0))); try done.
  - intros p Hp. apply elem_of_list_to_set, list_elem_of_fmap in Hp as (a & -> & _). by exists a.
