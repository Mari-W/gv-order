(** ** Strict worlds from a rank

    A world generated by facts L is strict when a rank rises along
    program order and along L. The rank reads each point through a map
    [cn] that sends generated aliases to one representative, so [cn]
    must respect ≡. [wgen_strict_by] takes the rank into any strict
    order, and the lemmas below instantiate it. *)

Lemma geq_cn (E : prel) (cn : point → point) x y :
  (∀ x, cn (pt_shift 1 x) = pt_shift 1 (cn x)) →
  (∀ x y i, cn x = cn y → cn (pt_slot x i) = cn (pt_slot y i)) →
  (∀ x y, E x y → cn x = cn y) →
  geq E x y → cn x = cn y.
Proof. intros Hs Hl HE. induction 1; try congruence; auto. Qed.

Lemma wgen_strict_by {A} (R : A → A → Prop) N E L (cn : point → point) (r : point → A) :
  (∀ a, ¬ R a a) → (∀ a b c, R a b → R b c → R a c) →
  (∀ p, p ∈ N → ∃ a, p = NConst a) →
  (∀ x y, E x y → eq_or_supp N x y) →
  (∀ x y, L x y → po_or_supp N x y) →
  (∀ x, cn (pt_shift 1 x) = pt_shift 1 (cn x)) →
  (∀ x y i, cn x = cn y → cn (pt_slot x i) = cn (pt_slot y i)) →
  (∀ x y, E x y → cn x = cn y) →
  (∀ x, R (r x) (r (pt_shift 1 x))) →
  (∀ x y, L x y → R (r (cn x)) (r (cn y))) →
  strict (wgen N E L).
Proof.
  intros Hirr Htr HN HE HL Hs Hl Hc Hr HLr. split; [by apply wgen_wf|].
  assert (∀ x y, glt E L x y → R (r (cn x)) (r (cn y))) as Hlt.
  { induction 1 as [x y H|x|x x' y y' Hx _ IH Hy|x y z _ IH1 _ IH2].
    - by apply HLr.
    - rewrite Hs. apply Hr.
    - apply (geq_cn E cn) in Hx, Hy; [|done..]. by rewrite Hx, <-Hy.
    - by eapply Htr. }
  intros x H. apply Hlt in H. exact (Hirr _ H).
Qed.

Lemma slot_respect (cn : point → point) :
  (∀ x i, cn (pt_slot x i) = pt_slot (cn x) i) →
  ∀ x y i, cn x = cn y → cn (pt_slot x i) = cn (pt_slot y i).
Proof. intros Hl x y i E. by rewrite !Hl, E. Qed.

Lemma wgen_strict N E L (cn : point → point) (r : point → nat) :
  (∀ p, p ∈ N → ∃ a, p = NConst a) →
  (∀ x y, E x y → eq_or_supp N x y) →
  (∀ x y, L x y → po_or_supp N x y) →
  (∀ x, cn (pt_shift 1 x) = pt_shift 1 (cn x)) →
  (∀ x i, cn (pt_slot x i) = pt_slot (cn x) i) →
  (∀ x y, E x y → cn x = cn y) →
  (∀ x, r x < r (pt_shift 1 x)) →
  (∀ x y, L x y → r (cn x) < r (cn y)) →
  strict (wgen N E L).
Proof.
  intros HN HE HL Hs Hl Hc Hr HLr.
  apply (wgen_strict_by lt N E L cn r); [intros a; lia|intros a b c; lia|exact HN|exact HE
    |exact HL|exact Hs|by apply slot_respect|exact Hc|exact Hr|exact HLr].
Qed.

(** Strictness when ≡ relates slots (Forwarder.v). The map [cn] has to
    respect slots and need not commute with them. *)
Lemma wgen_strict_cong N E L (cn : point → point) (r : point → nat) :
  (∀ p, p ∈ N → ∃ a, p = NConst a) →
  (∀ x y, E x y → eq_or_supp N x y) →
  (∀ x y, L x y → po_or_supp N x y) →
  (∀ x, cn (pt_shift 1 x) = pt_shift 1 (cn x)) →
  (∀ x y i, cn x = cn y → cn (pt_slot x i) = cn (pt_slot y i)) →
  (∀ x y, E x y → cn x = cn y) →
  (∀ x, r x < r (pt_shift 1 x)) →
  (∀ x y, L x y → r (cn x) < r (cn y)) →
  strict (wgen N E L).
Proof.
  intros HN HE HL Hs Hl Hc Hr HLr.
  apply (wgen_strict_by lt N E L cn r); [intros a; lia|intros a b c; lia|done..].
Qed.

(** A ceiling ζ above every instant of a channel has no rank in ℕ. A
    pair rank orders it after them (TailCall.v). *)
Definition lexlt (p q : nat * nat) : Prop := p.1 < q.1 ∨ (p.1 = q.1 ∧ p.2 < q.2).

Lemma wgen_strict_lex N E L (cn : point → point) (r : point → nat * nat) :
  (∀ p, p ∈ N → ∃ a, p = NConst a) →
  (∀ x y, E x y → eq_or_supp N x y) →
  (∀ x y, L x y → po_or_supp N x y) →
  (∀ x, cn (pt_shift 1 x) = pt_shift 1 (cn x)) →
  (∀ x i, cn (pt_slot x i) = pt_slot (cn x) i) →
  (∀ x y, E x y → cn x = cn y) →
  (∀ x, lexlt (r x) (r (pt_shift 1 x))) →
  (∀ x y, L x y → lexlt (r (cn x)) (r (cn y))) →
  strict (wgen N E L).
Proof.
  intros HN HE HL Hs Hl Hc Hr HLr.
  apply (wgen_strict_by lexlt N E L cn r); [intros a; unfold lexlt; lia
    |intros a b c; unfold lexlt; lia|exact HN|exact HE
    |exact HL|exact Hs|by apply slot_respect|exact Hc|exact Hr|exact HLr].
Qed.

(** ** Ranks into ℤ with a top element

    Levels of Padovani and Novara fall and rise without bound, and a
    latent effect ⊤ needs a ceiling above every level (pn/PNWorld.v). A
    rank is a pair of an integer level and an instant, read
    lexicographically, or a top element with an instant above all of
    them. *)
Inductive zrank := ZR (z : Z) (k : nat) | ZT (k : nat).

Definition zlt (a b : zrank) : Prop :=
  match a, b with
  | ZR z k, ZR z' k' => (z < z')%Z ∨ (z = z' ∧ k < k')
  | ZR _ _, ZT _ => True
  | ZT k, ZT k' => k < k'
  | ZT _, ZR _ _ => False
  end.

Lemma zlt_irrefl a : ¬ zlt a a.
Proof. destruct a; simpl; lia. Qed.

Lemma zlt_trans a b c : zlt a b → zlt b c → zlt a c.
Proof. destruct a, b, c; simpl; lia. Qed.

Lemma wgen_strict_z N E L (cn : point → point) (r : point → zrank) :
  (∀ p, p ∈ N → ∃ a, p = NConst a) →
  (∀ x y, E x y → eq_or_supp N x y) →
  (∀ x y, L x y → po_or_supp N x y) →
  (∀ x, cn (pt_shift 1 x) = pt_shift 1 (cn x)) →
  (∀ x y i, cn x = cn y → cn (pt_slot x i) = cn (pt_slot y i)) →
  (∀ x y, E x y → cn x = cn y) →
  (∀ x, zlt (r x) (r (pt_shift 1 x))) →
  (∀ x y, L x y → zlt (r (cn x)) (r (cn y))) →
  strict (wgen N E L).
Proof. apply wgen_strict_by; [apply zlt_irrefl|apply zlt_trans]. Qed.

(** Strictness through a denotation of points that commutes with
    successor and slots. ≡ facts relate points with one denotation, and
    the rank of a denotation rises along successor and along ≺ facts.
    The denotation need not be a point, so aliases need no
    representative (pn/PNWorld.v). *)
Lemma wgen_strict_den {D A} (R : A → A → Prop) N E L (den : point → D)
    (dsh : D → D) (dsl : D → nat → D) (r : D → A) :
  (∀ a, ¬ R a a) → (∀ a b c, R a b → R b c → R a c) →
  (∀ p, p ∈ N → ∃ a, p = NConst a) →
  (∀ x y, E x y → eq_or_supp N x y) →
  (∀ x y, L x y → po_or_supp N x y) →
  (∀ x, den (pt_shift 1 x) = dsh (den x)) →
  (∀ x i, den (pt_slot x i) = dsl (den x) i) →
  (∀ x y, E x y → den x = den y) →
  (∀ d, R (r d) (r (dsh d))) →
  (∀ x y, L x y → R (r (den x)) (r (den y))) →
  strict (wgen N E L).
Proof.
  intros Hirr Htr HN HE HL Hs Hl Hc Hr HLr. split; [by apply wgen_wf|].
  assert (∀ x y, geq E x y → den x = den y) as Heq.
  { induction 1; try congruence; auto; rewrite ?Hs, ?Hl; congruence. }
  assert (∀ x y, glt E L x y → R (r (den x)) (r (den y))) as Hlt.
  { induction 1 as [x y H|x|x x' y y' Hx _ IH Hy|x y z _ IH1 _ IH2].
    - by apply HLr.
    - rewrite Hs. apply Hr.
    - apply Heq in Hx, Hy. by rewrite Hx, <-Hy.
    - by eapply Htr. }
  intros x H. apply Hlt in H. exact (Hirr _ H).
Qed.

(** A top-level constraint is acyclic when a rank rises along program
    order and along its ≺ facts and its ≡ facts keep the denotation
    (sharp edges 110). *)
Lemma c0_acyclic_den {D A} (R : A → A → Prop) n P (den : point → D)
    (dsh : D → D) (dsl : D → nat → D) (r : D → A) :
  (∀ a, ¬ R a a) → (∀ a b c, R a b → R b c → R a c) →
  (∀ x, den (pt_shift 1 x) = dsh (den x)) →
  (∀ x i, den (pt_slot x i) = dsl (den x) i) →
  (∀ x y, P (FEq x y) → den x = den y) →
  (∀ d, R (r d) (r (dsh d))) →
  (∀ x y, P (FLt x y) → R (r (den x)) (r (den y))) →
  c0_acyclic n (BCs [] P).
Proof.
  intros Hirr Htr Hs Hl HE Hr HL. split; [done|].
  assert (∀ x y, geq (c0_eq n (BCs [] P)) x y → den x = den y) as Heq.
  { induction 1 as [x y H| | | | |]; try congruence; rewrite ?Hs, ?Hl; try congruence.
    apply bcs_open_nil in H as [H _]. by apply HE. }
  assert (∀ x y, glt (c0_eq n (BCs [] P)) (c0_lt n (BCs [] P)) x y → R (r (den x)) (r (den y))) as Hlt.
  { induction 1 as [x y H|x|x x' y y' Hx _ IH Hy|x y z _ IH1 _ IH2].
    - apply bcs_open_nil in H as [H _]. by apply HL.
    - rewrite Hs. apply Hr.
    - apply Heq in Hx, Hy. by rewrite Hx, <-Hy.
    - by eapply Htr. }
  intros p H. exact (Hirr _ (Hlt _ _ H)).
Qed.

(** The same with a rank into ℕ and no ≡ facts. *)
Lemma c0_acyclic_rank n P (r : point → nat) :
  (∀ x, r x < r (pt_shift 1 x)) →
  (∀ x y, ¬ P (FEq x y)) → (∀ x y, P (FLt x y) → r x < r y) →
  c0_acyclic n (BCs [] P).
Proof.
  intros Hr HE HL. apply (c0_acyclic_den lt n P id (pt_shift 1) pt_slot r); try done.
  - intros a. lia.
  - intros a b c. lia.
  - intros x y H. by destruct (HE x y).
Qed.

(** A rank for top-level variables: w per variable index, one per step. *)
Fixpoint pn_vidx (p : pname) : nat :=
  match p with NVar a => a | NConst _ => 0 | NSlot q _ _ => pn_vidx q end.

Definition vrank (w : nat) (x : point) : nat := w * pn_vidx (pt_name x) + pt_off x.

Lemma vrank_shift w x : vrank w x < vrank w (pt_shift 1 x).
Proof. unfold vrank, pt_shift. simpl. lia. Qed.

(** The rank of a point is a weight per root constant, slots weighted
    by their base, plus a step per name times the offset. *)
Fixpoint pn_rank (g : nat → nat) (h : nat → nat → nat → nat) (p : pname) : nat :=
  match p with
  | NConst a => g a
  | NVar _ => 0
  | NSlot q b i => h (pn_rank g h q) b i
  end.

Definition prank (k : pname → nat) (g : nat → nat) (h : nat → nat → nat → nat) (x : point) : nat :=
  pn_rank g h (pt_name x) + k (pt_name x) * S (pt_off x).

Lemma prank_shift k g h x : (∀ p, 0 < k p) → prank k g h x < prank k g h (pt_shift 1 x).
Proof. intros Hk. specialize (Hk (pt_name x)). unfold prank, pt_shift. simpl. nia. Qed.

(** ** Splitting linear environments by occurrence

    The derivations below never name Δ₁ and Δ₂. [lp e x Δ] keeps the
    unlimited bindings of Δ and the linear ones that occur in e, with
    x the index of Δ's head inside e. [sok] checks that every linear
    binding goes to exactly one side. *)

Fixpoint occ (x : nat) (e : expr) : bool :=
  match e with
  | Var y => Nat.eqb x y
  | EUnit | Konst _ | Chan _ => false
  | Lam e | EBox e => occ (S x) e
  | App e1 e2 | Pair e1 e2 | LetU e1 e2 => occ x e1 || occ x e2
  | LetP e1 e2 => occ x e1 || occ (S (S x)) e2
  | Inj1 e | Inj2 e => occ x e
  | Case e e1 e2 => occ x e || occ (S x) e1 || occ (S x) e2
  end.

Definition unlb (T : ty) : bool := match T with TBox _ _ _ => true | _ => false end.

Lemma unlb_unl T : unlb T = true → unlimited T.
Proof. by destruct T. Qed.

Fixpoint lp (e : expr) (x : nat) (Δ : lenv) : lenv :=
  match Δ with
  | [] => []
  | None :: Δ' => None :: lp e (S x) Δ'
  | Some T :: Δ' => (if unlb T || occ x e then Some T else None) :: lp e (S x) Δ'
  end.

Fixpoint sok (e1 : expr) (x1 : nat) (e2 : expr) (x2 : nat) (Δ : lenv) : bool :=
  match Δ with
  | [] => true
  | None :: Δ' => sok e1 (S x1) e2 (S x2) Δ'
  | Some T :: Δ' => (unlb T || xorb (occ x1 e1) (occ x2 e2)) && sok e1 (S x1) e2 (S x2) Δ'
  end.

Lemma lp_split e1 x1 e2 x2 Δ :
  sok e1 x1 e2 x2 Δ = true → lenv_split Δ (lp e1 x1 Δ) (lp e2 x2 Δ).
Proof.
  revert x1 x2. induction Δ as [|[T|] Δ IH]; intros x1 x2 H; simpl in *; [constructor| |].
  - apply andb_true_iff in H as [H1 H2].
    destruct (unlb T) eqn:Hu; simpl.
    + apply lsplit_unl; [by apply unlb_unl|by apply IH].
    + destruct (occ x1 e1), (occ x2 e2); simpl in *; try done;
        [apply lsplit_l|apply lsplit_r]; by apply IH.
  - apply lsplit_none. by apply IH.
Qed.

Fixpoint allunl (Δ : lenv) : bool :=
  match Δ with
  | [] => true
  | None :: Δ' => allunl Δ'
  | Some T :: Δ' => unlb T && allunl Δ'
  end.

Fixpoint lonly (x : nat) (Δ : lenv) : lenv :=
  match Δ, x with
  | [], _ => []
  | o :: Δ', 0 => o :: lenv_nones Δ'
  | _ :: Δ', S x' => None :: lonly x' Δ'
  end.

Fixpoint oku (x : nat) (Δ : lenv) : bool :=
  match Δ, x with
  | [], _ => true
  | _ :: Δ', 0 => allunl Δ'
  | o :: Δ', S x' => match o with Some T => unlb T | None => true end && oku x' Δ'
  end.

Lemma nones_wk Δ : allunl Δ = true → lenv_wk (lenv_nones Δ) Δ.
Proof.
  induction Δ as [|[T|] Δ IH]; simpl; intros H; [constructor| |].
  - apply andb_true_iff in H as [H1 H2]. apply lwk_drop; [by apply unlb_unl|by apply IH].
  - apply lwk_cons. by apply IH.
Qed.

Lemma lonly_wk x Δ : oku x Δ = true → lenv_wk (lonly x Δ) Δ.
Proof.
  revert x. induction Δ as [|o Δ IH]; intros [|x] H; simpl in *; [constructor|constructor| |].
  - apply lwk_cons. by apply nones_wk.
  - apply andb_true_iff in H as [H1 H2]. destruct o as [T|].
    + apply lwk_drop; [by apply unlb_unl|by apply IH].
    + apply lwk_cons. by apply IH.
Qed.

Lemma lonly_only x Δ T : Δ !! x = Some (Some T) → lenv_only (lonly x Δ) x T.
Proof.
  revert x. induction Δ as [|o Δ IH]; intros [|x] H; simpl in *; [done|done| |].
  - simplify_eq. split; [done|]. intros [|y] T' Hy; simpl in Hy; [by simplify_eq|].
    exfalso. apply list_elem_of_lookup_2 in Hy. apply lenv_empty_nones in Hy. done.
  - destruct (IH x H) as [H1 H2]. split; [done|]. intros [|y] T' Hy; simpl in Hy; [done|].
    destruct (H2 y T' Hy). split; [lia|done].
Qed.

Lemma allunl_unl Δ : allunl Δ = true → lenv_unl Δ.
Proof.
  induction Δ as [|[T|] Δ IH]; simpl; intros H o Ho; [by apply elem_of_nil in Ho| |].
  - apply andb_true_iff in H as [H1 H2]. apply elem_of_cons in Ho as [->|Ho].
    + right. exists T. split; [done|by apply unlb_unl].
    + by apply IH.
  - apply elem_of_cons in Ho as [->|Ho]; [by left|by apply IH].
Qed.

(** ** Derived rules for Θ = ∅ *)

Section rules.
  Context (W : world) (HW : world_wf W).

  Lemma comp0 Ψ : tenv_comp (seqs W Ψ) ∅ ∅ ∅.
  Proof. apply tenv_comp_empty_l. intros ? ?. apply se_sym. Qed.

  Lemma tenv_heads0 : tenv_heads ∅ = ∅.
  Proof. unfold tenv_heads. by rewrite map_fold_empty. Qed.

  Lemma tv_var Φ Ψ Δ F x T :
    Δ !! x = Some (Some T) → oku x Δ = true → typed W Φ Ψ ∅ Δ F (Var x) T.
  Proof. intros H1 H2. eapply t_wk; [by apply lonly_wk|]. apply t_var. by apply lonly_only. Qed.

  Lemma tv_unit Φ Ψ Δ F : allunl Δ = true → typed W Φ Ψ ∅ Δ F EUnit TUnit.
  Proof. intros H. eapply t_wk; [by apply nones_wk|]. apply t_unit, lenv_empty_nones. Qed.

  Lemma tv_app Φ Ψ Δ F e1 e2 ub lb T U :
    sok e1 0 e2 0 Δ && negb (lenv_bot (lp e2 0 Δ)) = true →
    typed W Φ Ψ ∅ (lp e1 0 Δ) (sf_union F (lenv_heads (lp e2 0 Δ))) e1 (TLolli ub lb T U) →
    typed W Φ Ψ ∅ (lp e2 0 Δ) (sf_union F (opt_heads lb)) e2 T →
    ub_below_s W Ψ Φ ub F →
    typed W Φ Ψ ∅ Δ F (App e1 e2) U.
  Proof.
    intros Hs H1 H2 Hu. apply andb_true_iff in Hs as [Hs Hb]. apply negb_true_iff in Hb.
    eapply t_app; [apply comp0|by apply lp_split|exact Hu| |exact H2].
    by rewrite Hb, tenv_heads0, union_empty_l_L.
  Qed.

  (** A constant applied: its type is given by [konst_ty], the
      argument comes first so that its type is known. *)
  Lemma tv_appk Φ Ψ Δ F k e2 ub T U :
    typed W Φ Ψ ∅ Δ F e2 T →
    konst_ty (seqs W Ψ) (slt W Ψ) (skn W Ψ) k (TLolli ub None T U) →
    ub_below_s W Ψ Φ ub F →
    typed W Φ Ψ ∅ Δ F (App (Konst k) e2) U.
  Proof.
    intros H2 Hk Hu. eapply (t_app W Φ Ψ ∅ ∅ ∅ Δ (lenv_nones Δ) Δ F _ _ ub None).
    - apply comp0.
    - apply lenv_split_nones_l.
    - exact Hu.
    - apply t_konst; [apply lenv_empty_nones|done].
    - destruct F as [P o]. unfold sf_union. simpl. by rewrite union_empty_r_L.
  Qed.

  Lemma tv_pair Φ Ψ Δ F e1 e2 T U :
    sok e1 0 e2 0 Δ && negb (lenv_bot (lp e2 0 Δ)) = true →
    typed W Φ Ψ ∅ (lp e2 0 Δ) (sf_unionb F (heads T) (hbot T)) e2 U →
    typed W Φ Ψ ∅ (lp e1 0 Δ) (sf_union F (lenv_heads (lp e2 0 Δ))) e1 T →
    typed W Φ Ψ ∅ Δ F (Pair e1 e2) (TProd T U).
  Proof.
    intros Hs H2 H1. apply andb_true_iff in Hs as [Hs Hb]. apply negb_true_iff in Hb.
    eapply t_pair; [apply comp0|by apply lp_split| |exact H2].
    by rewrite Hb, tenv_heads0, union_empty_l_L.
  Qed.

  Lemma tv_letu Φ Ψ Δ F e1 e2 T :
    sok e1 0 e2 0 Δ && negb (lenv_bot (lp e2 0 Δ)) = true →
    typed W Φ Ψ ∅ (lp e1 0 Δ) (sf_union F (lenv_heads (lp e2 0 Δ))) e1 TUnit →
    typed W Φ Ψ ∅ (lp e2 0 Δ) F e2 T →
    typed W Φ Ψ ∅ Δ F (LetU e1 e2) T.
  Proof.
    intros Hs H1 H2. apply andb_true_iff in Hs as [Hs Hb]. apply negb_true_iff in Hb.
    eapply t_letu; [apply comp0|by apply lp_split| |exact H2].
    by rewrite Hb, tenv_heads0, union_empty_l_L.
  Qed.

  Lemma tv_letp Φ Ψ Δ F e1 e2 T1 T2 T :
    sok e1 0 e2 2 Δ && negb (lenv_bot (lp e2 2 Δ)) = true →
    typed W Φ Ψ ∅ (lp e1 0 Δ) (sf_union F (lenv_heads (lp e2 2 Δ))) e1 (TProd T1 T2) →
    typed W Φ Ψ ∅ (Some T2 :: Some T1 :: lp e2 2 Δ) F e2 T →
    typed W Φ Ψ ∅ Δ F (LetP e1 e2) T.
  Proof.
    intros Hs H1 H2. apply andb_true_iff in Hs as [Hs Hb]. apply negb_true_iff in Hb.
    eapply t_letp; [apply comp0|by apply lp_split| |exact H2].
    by rewrite Hb, tenv_heads0, union_empty_l_L.
  Qed.

  Lemma tv_lam Φ Ψ Δ F e T U ub lb φ :
    φ ∉ dom Φ →
    lb_below_hb W Ψ lb (lenv_heads Δ) (lenv_bot Δ) →
    typed W (<[φ := ub]> Φ) Ψ ∅ (Some T :: Δ) (∅, Some (FVar φ)) e U →
    typed W Φ Ψ ∅ Δ F (Lam e) (TLolli ub lb T U).
  Proof. intros Hφ Hl H. eapply t_lam; [exact Hφ| |exact H]. by rewrite tenv_heads0, union_empty_l_L. Qed.

End rules.

(** {u} ≺ F, split into the points of F and the frame variable. *)
Section frames.
  Context (W : world).

  Lemma ubs_intro Ψ Φ x P o :
    (∀ y, y ∈ P → slt W Ψ x y) →
    match o with
    | Some (FVar φ) => ∃ u, Φ !! φ = Some (Some u) ∧ sle W Ψ x u
    | Some (FBot _) => False
    | None => True
    end →
    ub_below_s W Ψ Φ (Some x) (P, o).
  Proof. apply ub_below_s_intro. Qed.

  Lemma ubs_none Ψ Φ F : ub_below_s W Ψ Φ None F.
  Proof. done. Qed.

  Lemma sle_refl Ψ x : world_wf W → sle W Ψ x x.
  Proof. intros HW. left. apply se_refl. Qed.

