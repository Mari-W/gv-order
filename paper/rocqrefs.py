#!/usr/bin/env python3
"""Link paper claims to the mechanization, by name rather than by line.

    gen    scan theories/*.v and write paper/rocqrefs.tex
    check  scan the .tex sources and fail if any \\rocq{name} has no
           corresponding declaration

Names are resolved at build time, so a lemma may move within its file
without rotting the reference; renaming or deleting one breaks `check`,
which is the point.  The base URL is set once in the .tex (see
rocqrefs.sty) so the anonymized and the deanonymized build differ in a
single line.
"""

import re
import sys
import glob
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

DECL = re.compile(
    r'^\s*(?:Lemma|Theorem|Corollary|Definition|Example|Inductive|Fixpoint|'
    r'Instance|Record|Notation)\s+([A-Za-z_][A-Za-z0-9_\']*)')

USE = re.compile(r'\\rocq\{([^}]*)\}')


def declarations():
    """name -> (file relative to repo root, 1-based line)"""
    out = {}
    for path in sorted(glob.glob(os.path.join(ROOT, 'theories', '*.v'))):
        rel = os.path.relpath(path, ROOT)
        with open(path, encoding='utf-8') as f:
            for i, line in enumerate(f, start=1):
                m = DECL.match(line)
                if m and m.group(1) not in out:
                    out[m.group(1)] = (rel, i)
    return out


def escape(s):
    return s.replace('_', r'\_')


def gen():
    decls = declarations()
    dest = os.path.join(ROOT, 'paper', 'rocqrefs.tex')
    with open(dest, 'w', encoding='utf-8') as f:
        f.write('% Generated by paper/rocqrefs.py -- do not edit.\n')
        f.write('% One entry per top-level declaration in theories/.\n')
        for name, (rel, line) in sorted(decls.items()):
            f.write('\\rocqdef{%s}{%s}{%d}\n' % (name, rel, line))
    print('wrote %s (%d declarations)' % (
        os.path.relpath(dest, ROOT), len(decls)))


def check():
    decls = declarations()
    bad = []
    for path in sorted(glob.glob(os.path.join(ROOT, 'paper', '*.tex'))):
        if os.path.basename(path) == 'rocqrefs.tex':
            continue
        with open(path, encoding='utf-8') as f:
            for i, line in enumerate(f, start=1):
                for name in USE.findall(line):
                    if name not in decls:
                        bad.append((os.path.relpath(path, ROOT), i, name))
    for path, line, name in bad:
        print('%s:%d: no such declaration: %s' % (path, line, name),
              file=sys.stderr)
    if bad:
        print('%d unresolved reference(s)' % len(bad), file=sys.stderr)
        return 1
    print('all \\rocq{...} references resolve')
    return 0


if __name__ == '__main__':
    cmd = sys.argv[1] if len(sys.argv) > 1 else 'gen'
    if cmd == 'gen':
        gen()
    elif cmd == 'check':
        sys.exit(check())
    else:
        print(__doc__, file=sys.stderr)
        sys.exit(2)
