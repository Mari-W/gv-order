#!/usr/bin/env python3
"""Link paper claims to the mechanization, by name, with permalinks.

    gen [--base URL]   scan theories/*.v and write paper/rocqrefs.tex
    check              fail if any \\rocq{name} has no declaration

Everything is regenerated from the working tree: the declarations, their
current lines, and the permalink base, which is derived from the git
remote and the HEAD commit.  Re-run `gen` after any change to theories/
and the links follow.

The base pins a COMMIT, not a branch, so a link keeps pointing at the
code the paper described even after the branch moves on.  Pass --base to
override it -- that is how the anonymized build is produced:

    python3 paper/rocqrefs.py gen --base https://anonymous.4open.science/r/XXXX/
"""

import re
import sys
import glob
import os
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

DECL = re.compile(
    r'^\s*(?:Lemma|Theorem|Corollary|Definition|Example|Inductive|Fixpoint|'
    r'Instance|Record|Notation)\s+([A-Za-z_][A-Za-z0-9_\']*)')

USE = re.compile(r'\\rocq(?:as)?\{[^}]*\}?\{?([A-Za-z_][A-Za-z0-9_\']*)\}?')
USE_PLAIN = re.compile(r'\\rocq\{([^}]*)\}')
USE_AS = re.compile(r'\\rocqas\{[^}]*\}\{([^}]*)\}')


def git(*args):
    try:
        return subprocess.check_output(
            ['git'] + list(args), cwd=ROOT,
            stderr=subprocess.DEVNULL).decode().strip()
    except Exception:
        return ''


def permalink_base():
    """https://github.com/<owner>/<repo>/blob/<sha>/ for the current HEAD."""
    sha = git('rev-parse', 'HEAD')
    url = git('config', '--get', 'remote.origin.url')
    if not sha or not url:
        return ''
    # git@github.com:owner/repo.git  ->  https://github.com/owner/repo
    m = re.match(r'(?:git@|https://)([^:/]+)[:/](.+?)(?:\.git)?$', url)
    if not m:
        return ''
    return 'https://%s/%s/blob/%s/' % (m.group(1), m.group(2), sha)


def declarations():
    """name -> (path relative to root, module name, 1-based line)"""
    out = {}
    for path in sorted(glob.glob(os.path.join(ROOT, 'theories', '*.v'))):
        rel = os.path.relpath(path, ROOT)
        base = os.path.splitext(os.path.basename(path))[0]
        with open(path, encoding='utf-8') as f:
            for i, line in enumerate(f, start=1):
                m = DECL.match(line)
                if m and m.group(1) not in out:
                    out[m.group(1)] = (rel, base, i)
    return out


def gen(base=None):
    decls = declarations()
    if base is None:
        base = permalink_base()
        if git('status', '--porcelain'):
            print('warning: working tree is dirty; the permalinks will point '
                  'at HEAD, which does not contain your uncommitted changes',
                  file=sys.stderr)
    dest = os.path.join(ROOT, 'paper', 'rocqrefs.tex')
    with open(dest, 'w', encoding='utf-8') as f:
        f.write('%% Generated by paper/rocqrefs.py -- do not edit.\n')
        f.write('%% Regenerate with: make -C paper refs\n')
        if base:
            f.write('\\rocqsetbase{%s}\n' % base)
        for name, (rel, bn, line) in sorted(decls.items()):
            f.write('\\rocqdef{%s}{%s}{%s}{%d}\n' % (name, rel, bn, line))
    print('wrote %s (%d declarations)' % (
        os.path.relpath(dest, ROOT), len(decls)))
    print('base: %s' % (base or '(none -- names typeset inert)'))


def check():
    decls = declarations()
    bad = []
    for path in sorted(glob.glob(os.path.join(ROOT, 'paper', '*.tex'))):
        if os.path.basename(path) == 'rocqrefs.tex':
            continue
        with open(path, encoding='utf-8') as f:
            for i, line in enumerate(f, start=1):
                for name in USE_PLAIN.findall(line) + USE_AS.findall(line):
                    if name not in decls:
                        bad.append((os.path.relpath(path, ROOT), i, name))
    for path, line, name in bad:
        print('%s:%d: no such declaration: %s' % (path, line, name),
              file=sys.stderr)
    if bad:
        print('%d unresolved reference(s)' % len(bad), file=sys.stderr)
        return 1
    print('all \\rocq{...} references resolve')
    return 0


if __name__ == '__main__':
    argv = sys.argv[1:]
    cmd = argv[0] if argv else 'gen'
    if cmd == 'gen':
        base = None
        if '--base' in argv:
            base = argv[argv.index('--base') + 1]
        gen(base)
    elif cmd == 'check':
        sys.exit(check())
    else:
        print(__doc__, file=sys.stderr)
        sys.exit(2)
