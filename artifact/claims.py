#!/usr/bin/env python3
"""The table of paper claims and their Rocq declarations.

    python3 artifact/claims.py            print the table (Markdown)
    python3 artifact/claims.py --update   rewrite the table in ARTIFACT.md

Every \\rocq{name} and \\rocqas{text}{name} of paper/*.tex becomes a row,
resolved the way paper/rocqrefs.py resolves it (first declaration of the
name in theories/, constructors of inductives included).  The paper
element is the theorem-like environment around the reference, else the
caption or rule section on its line, else the enclosing (sub)section.
"""

import glob
import importlib.util

sys.dont_write_bytecode = True  # do not leave paper/__pycache__ behind
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BEGIN = '<!-- claims:begin (generated by artifact/claims.py) -->'
END = '<!-- claims:end -->'

ENVS = ('theorem', 'lemma', 'corollary', 'proposition', 'definition',
        'example', 'remark')
ENV_BEGIN = re.compile(r'\\begin\{(%s)\}(?:\[(.*)\])?' % '|'.join(ENVS))
ENV_END = re.compile(r'\\end\{(%s)\}' % '|'.join(ENVS))
SECTION = re.compile(r'\\(section|subsection|subsubsection|paragraph)\*?\{(.*?)\}')
CAPTION = re.compile(r'\\(caption|rulesection)\*?\{(.*)\}')
DECL = re.compile(
    r'^\s*(Lemma|Theorem|Corollary|Definition|Example|Inductive|Fixpoint|'
    r'Instance|Record|Notation)\s+([A-Za-z_][A-Za-z0-9_\']*)')


def load_rocqrefs():
    path = os.path.join(ROOT, 'paper', 'rocqrefs.py')
    spec = importlib.util.spec_from_file_location('rocqrefs', path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def clean(tex):
    """A short plain-text rendering of a LaTeX fragment."""
    tex = re.sub(r'\\rocq(?:as)?\{[^}]*\}(?:\{[^}]*\})?', '', tex)
    tex = re.sub(r'\\ref\{rule:([^}]*)\}', r'\1', tex)
    tex = re.sub(r'\\(?:ref|cref|label)\{[^}]*\}', '', tex)
    tex = tex.replace('\\OurLang', 'GV♯')
    tex = re.sub(r'\$[^$]*\$', '', tex)
    tex = re.sub(r'\\[A-Za-z]+\*?', '', tex)
    tex = re.sub(r'[{}~]', ' ', tex)
    tex = re.sub(r'\s+', ' ', tex)
    tex = re.sub(r'\s*,(\s*,)*\s*', ', ', tex).strip(' ,:;()')
    return tex.replace('|', '/')


def kind_of(rel, line):
    with open(os.path.join(ROOT, rel), encoding='utf-8') as f:
        for i, text in enumerate(f, start=1):
            if i == line:
                m = DECL.match(text)
                return m.group(1) if m else 'Constructor'
    return '?'


def module_of(rel):
    parts = os.path.splitext(rel)[0].split(os.sep)
    return '.'.join(['LRGV'] + parts[1:])


def rows():
    rr = load_rocqrefs()
    decls = rr.declarations()
    out = []
    for path in sorted(glob.glob(os.path.join(ROOT, 'paper', '*.tex'))):
        if os.path.basename(path) == 'rocqrefs.tex':
            continue
        tex = os.path.relpath(path, ROOT)
        env = None
        section = ''
        seen = set()
        with open(path, encoding='utf-8') as f:
            for i, line in enumerate(f, start=1):
                m = SECTION.search(line)
                if m:
                    section = clean(m.group(2))
                m = ENV_BEGIN.search(line)
                if m:
                    title = clean(m.group(2) or '')
                    env = m.group(1).capitalize() + (' (%s)' % title
                                                     if title else '')
                names = rr.USE_PLAIN.findall(line) + rr.USE_AS.findall(line)
                if names:
                    if env:
                        where = env
                    else:
                        c = CAPTION.search(line)
                        where = (clean(c.group(2)) if c else '') or \
                            ('§ ' + section if section else '')
                        if c and c.group(1) == 'caption':
                            where = 'Figure (%s)' % where
                    for name in names:
                        if (name, where) in seen:
                            continue
                        seen.add((name, where))
                        if name in decls:
                            rel, _, dline = decls[name]
                            out.append((tex, i, where, name,
                                        kind_of(rel, dline),
                                        '%s:%d' % (rel, dline),
                                        module_of(rel)))
                        else:
                            out.append((tex, i, where, name, 'unresolved',
                                        '(no declaration)', ''))
                if ENV_END.search(line):
                    env = None
    return out


def table():
    lines = ['| Paper | Element | Rocq name | Kind | Location |',
             '|---|---|---|---|---|']
    for tex, i, where, name, kind, loc, mod in rows():
        lines.append('| %s:%d | %s | `%s` | %s | %s |' % (
            os.path.basename(tex), i, where or '', name, kind,
            ('`%s`' % loc) if mod else '**' + loc + '**'))
    return '\n'.join(lines) + '\n'


def main():
    t = table()
    if '--update' in sys.argv[1:]:
        p = os.path.join(ROOT, 'ARTIFACT.md')
        with open(p, encoding='utf-8') as f:
            s = f.read()
        a, b = s.index(BEGIN) + len(BEGIN), s.index(END)
        s = s[:a] + '\n' + t + s[b:]
        with open(p, 'w', encoding='utf-8') as f:
            f.write(s)
        print('updated ARTIFACT.md')
    else:
        sys.stdout.write(t)


if __name__ == '__main__':
    main()
